#!/usr/bin/env python3

# Added after cambc's release command (-O3 -DNDEBUG -std=c++20 -msimd128 ...), so
# they win over it; e.g. ["-mllvm", "-inline-threshold=5000"].
FLAGS: list[str] = []

"""Submit this bot as WebAssembly assembly instead of C++ source.

Each .cpp in src/ is compiled to assembly with cambc's own release compile command
(the one the platform builds with) plus FLAGS, and written straight into
build/<bot>/src/ (its own folder dropped: the assembly includes nothing) as a C++
file holding nothing but a top-level __asm__. The platform then only assembles and
links it. The submission is built here first, and with no FLAGS it must come out
byte-identical to the plain release build. Then it asks before uploading it with
`cambc submit`, adding two folders the website's file list shows: src/<bot>/ and
src/submitted_<Calgary time>/ (each holds an empty .keep: cambc leaves out empty
folders).

The SDK is compiled into the assembly here, so the submission keeps the SDK of
the cambc installed now: update cambc before submitting.

  ./submit.py
"""

if True:
    from pathlib import Path
    import sys
    import subprocess
    import shutil
    import shlex
    import json
    from datetime import datetime
    from zoneinfo import ZoneInfo


BOT = Path(__file__).resolve().parent
# Named after the bot, so the upload has the name a plain `cambc submit` of it would.
SUBMISSION = BOT / "build" / BOT.name
ASM = BOT / "build" / "asm"
# The compiler writes these two sections for the file the assembly ends up in, so
# the assembly's own copies would be duplicates (wasm-ld refuses a second producers).
METADATA = (".custom_section.producers", ".custom_section.target_features")
END = ')ASM"'


def run(args, cwd=BOT):
    args = [str(a) for a in args]
    print(f"$ {shlex.join(args)}", flush=True)
    if subprocess.run(args, cwd=cwd).returncode:
        sys.exit(f"failed: {shlex.join(args)}")


def release_build(bot):
    """Build `bot` as the platform does and return its release build directory."""
    run(["cambc", "build", bot, "--release"])
    return bot / ".cambc" / "build-release"


def assembly_command(entry, out):
    """The release compile command of one source file, writing assembly to `out` instead."""
    args = shlex.split(entry["command"])
    assert "-DCAMBC_DEBUG" not in args, "a debug build's command"
    i = args.index("-o")
    del args[i:i + 2]
    args.remove("-c")
    args.remove(entry["file"])
    return [*args, *FLAGS, "-S", "-o", out, entry["file"]]


def without_metadata(asm):
    kept, skip = [], False
    for line in asm.split("\n"):
        words = line.split()
        if words[:1] == [".section"]:
            skip = words[1].split(",")[0] in METADATA
        if not skip:
            kept.append(line)
    return "\n".join(kept)


def add_labels():
    """src/<bot>/ and src/submitted_<Calgary time>/, for the website's file list."""
    when = datetime.now(ZoneInfo("America/Edmonton")).strftime("%Y-%m-%d_%H-%M_%Z")
    for name in (BOT.name, f"submitted_{when}"):
        folder = SUBMISSION / "src" / name
        folder.mkdir()
        (folder / ".keep").touch()
        print(f"added {folder.relative_to(BOT)}/")


def main():
    print(f"== building {BOT.name} as cambc does, for its compile commands")
    plain = release_build(BOT)
    shutil.rmtree(SUBMISSION, ignore_errors=True)
    entries = json.loads((plain / "compile_commands.json").read_text())
    names = [Path(e["file"]).name for e in entries]
    assert len(set(names)) == len(names), f"two sources share a name, so src/ cannot be flat: {names}"
    for entry in entries:
        source = Path(entry["file"]).relative_to(BOT / "src")
        asm = ASM / source.with_suffix(".s")
        asm.parent.mkdir(parents=True, exist_ok=True)
        print(f"\n== compiling src/{source} to assembly")
        print(f"FLAGS: {shlex.join(FLAGS) or '(none: the platform build)'}")
        run(assembly_command(entry, asm), cwd=entry["directory"])
        body = without_metadata(asm.read_text())
        assert END not in body, f"{asm} holds the raw string's end"
        out = SUBMISSION / "src" / source.name
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(f"// Generated by submit.py from {BOT.name}/src/{source}, flags {shlex.join(FLAGS) or '(none)'}.\n"
                       f'__asm__(R"ASM(\n{body}\n{END});\n')
        print(f"wrote {out.relative_to(BOT)}: {out.stat().st_size // 1024} KB")

    print("\n== building the submission")
    built = release_build(SUBMISSION) / "bot-injected.wasm"
    if not FLAGS and built.read_bytes() != (plain / "bot-injected.wasm").read_bytes():
        sys.exit(
            f"{built} differs from the plain release build, though FLAGS is empty")
    print(f"built: {built.stat().st_size // 1024} KB of wasm" +
          ("" if FLAGS else ", the same as the plain build"))

    print()
    if input(f"Submit {SUBMISSION.relative_to(BOT)}? [y/N] ").strip().lower() in ("y", "yes"):
        add_labels()
        run(["cambc", "submit", SUBMISSION])
    else:
        print(f"Not submitted. To submit later: cambc submit {SUBMISSION}")


if __name__ == "__main__":
    main()
