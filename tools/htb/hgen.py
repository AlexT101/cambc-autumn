#!/usr/bin/env python3
"""Write C++ bots like Java; hgen turns them into the C++ that cambc builds.

Put your .htb files straight in the bot folder (bots/<bot>/*.htb, and any
subfolders) and write them like Java (an .htb file is C++): classes with their methods inside, no
headers, no forward declarations, in any order. Every file can use what any
other file defines. Functions marked `inline`, `constexpr` or `consteval` are
kept whole in a header (methods: in their class) instead of src/<name>.inl,
and can still call each other in any order.

hgen generates src/, which is what cambc compiles and submits:
  src/headers/<name>.h   what <name>.htb declares: its classes (with method
                         declarations), enums, constants, globals, function
                         prototypes and templates
  src/headers/<name>.inline.h
                         its inline functions and templates, defined after
                         every class (their bodies may reach any class)
  src/<name>.inl         the bodies of <name>.htb's functions and methods
  src/unity.cpp          every header, then every body, as one translation
                         unit, so the compiler can inline calls across files
Compile errors point at your files and lines, not at src/. Headers in the bot
folder (.h, .hpp) are copied into src/ as they are.

Your editor understands your files too: hgen writes what each file can see
into .cambc/hgen/ and points clangd at it from the bot's .clangd.
In VS Code, install the HTB extension (python3 tools/htb/install.py) for
squiggles, completion and go to definition in .htb files; tools/htb/htbcheck.py
checks a bot from the command line.

Good to know:
  - The whole bot is compiled together, so two files can't both have a
    `static` function or global with the same name, and a file-level
    `using namespace` reaches every file (hgen notes both).
  - Every file sees the library headers (<...>) any file includes.
  - Globals start up after the globals their initializers read, including
    through the functions and constructors they call.
  - `#if`/`#ifdef` around code works anywhere (`#ifdef CAMBC_DEBUG` for
    debug-only code): whatever hgen moves keeps its conditions. `#if 0` is
    left out, and include guards are fine.
  - Forgot the `;` after a class (Java has none)? hgen adds it and says so.
  - Each file's macros keep their own values, even if another file defines
    the same macro.
  - In the editor, a nested class used above its definition in the same class
    is underlined, although it builds: clangd reads the class as written.
  - Never edit src/: hgen rewrites it, and won't touch a src/ holding files it
    didn't write.

Run it before `cambc build`, `cambc run` and `cambc submit`, or leave --watch
running while you work.
"""

