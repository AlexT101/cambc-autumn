class Tok:
    __slots__ = ("kind", "text", "start", "end")

    def __init__(self, kind, text, start, end):
        self.kind, self.text, self.start, self.end = kind, text, start, end


def _quoted_end(src, i):
    quote, k, n = src[i], i + 1, len(src)
    while k < n:
        c = src[k]
        if c == "\\":
            k += 2
        elif c == quote:
            k += 1
            break
        elif c == "\n":
            break
        else:
            k += 1
    return _SUFFIX.match(src, min(k, n)).end()


def _raw_end(src, i):
    paren = src.find("(", i)
    if paren < 0:
        return len(src)
    close = ")" + src[i + 1:paren] + '"'
    end = src.find(close, paren + 1)
    return len(src) if end < 0 else _SUFFIX.match(src, end + len(close)).end()


def _directive_end(src, i):
    n, k = len(src), i
    while k < n:
        c = src[k]
        if c == "\n":
            break
        if c == "\\" and src.startswith("\n", k + 1):
            k += 2
        elif src.startswith("/*", k):
            end = src.find("*/", k + 2)
            k = n if end < 0 else end + 2
        elif src.startswith("//", k):
            end = src.find("\n", k)
            k = n if end < 0 else end
        elif c in "\"'":
            k = _quoted_end(src, k)
        else:
            k += 1
    return k


def tokenize(src):
    """Split C++ source into tokens; comments are returned separately."""
    toks, comments = [], []
    n, i, line_start = len(src), 0, True
    while i < n:
        m = _SCAN.match(src, i)
        kind, text, j = m.lastgroup, m.group(), m.end()
        if kind == "space":
            i = j
            continue
        if kind == "newline":
            line_start, i = True, j
            continue
        if kind == "comment":
            comments.append((i, j))
            i = j
            continue
        if text == "#" and line_start:
            j = _directive_end(src, i)
            toks.append(Tok("pp", src[i:j].rstrip(), i, j))
            i = j
            continue
        line_start = False
        if kind == "id" and j < n and src[j] in "\"'":
            if src[j] == '"' and text in ("R", "u8R", "uR", "UR", "LR"):
                j, kind = _raw_end(src, j), "str"
            elif text in ("u8", "u", "U", "L"):
                j, kind = _quoted_end(src, j), "str"
        elif kind == "quote":
            j, kind = _quoted_end(src, i), "str"
        elif kind in ("punct", "other"):
            kind = "p"
        toks.append(Tok(kind, src[i:j], i, j))
        i = j
    return toks, comments


def drop_disabled(toks):
    """Leave out what the compiler never sees anyway: code under `#if 0` (or the `#else` of
    `#if 1`), with those directives, and a whole-file include guard."""
    pp = [k for k, t in enumerate(toks) if t.kind == "pp" and not _PRAGMA_ONCE.match(t.text)]
    drop = set()
    if len(pp) >= 3 and pp[-1] == len(toks) - 1 and _ENDIF.match(toks[pp[-1]].text):
        m = _GUARD.match(toks[pp[0]].text)
        if m and pp[1] == pp[0] + 1 and re.fullmatch(rf"#\s*define\s+{m.group(1)}\s*", toks[pp[1]].text):
            depth = 0
            for k in pp:
                depth += 1 if _IF.match(toks[k].text) else -1 if _ENDIF.match(toks[k].text) else 0
                if depth == 0:
                    break
            if k == pp[-1]:     # the #ifndef's own #endif closes the file
                drop = {pp[0], pp[1], pp[-1]}
    out, stack = [], []     # per open #if: [shown (True/False, or None: the compiler decides), decided, taken]
    for k, t in enumerate(toks):
        if k in drop:
            continue
        live = all(f[0] is not False for f in stack)
        if t.kind == "pp":
            if _IF.match(t.text):
                m = _IF_CONST.match(t.text)
                if not live or m:
                    shown = live and m.group(1) in ("1", "true")
                    stack.append([shown, True, shown or not live])
                    continue
                stack.append([None, False, False])
            elif _ELSE.match(t.text) and stack and stack[-1][1]:
                f = stack[-1]
                if t.text.lstrip("# \t").startswith("else"):
                    f[0], f[2] = not f[2], True
                elif not f[2] and all(x[0] is not False for x in stack[:-1]):
                    # `#if 0 ... #elif COND`: COND's branch is an ordinary #if now
                    f[:] = [None, False, False]
                    out.append(Tok("pp", "#if" + t.text.lstrip("# \t")[4:], t.start, t.end))
                    continue
                else:
                    f[0] = False
                continue
            elif _ENDIF.match(t.text) and stack:
                if stack.pop()[1]:
                    continue
        if live:
            out.append(t)
    return out


class Toks(list):
    """A file's tokens; reading past either end gives an empty end-of-file token, so half-written
    code (hgen runs on every save) can't crash the parser."""

    def __init__(self, toks, size):
        super().__init__(toks)
        self.eof = Tok("eof", "", size, size)

    def __getitem__(self, k):
        if isinstance(k, int) and not 0 <= k < len(self):
            return self.eof
        return super().__getitem__(k)


def match_brackets(toks):
    pair, stack = [-1] * len(toks), []
    closer = {")": "(", "]": "[", "}": "{"}
    for i, t in enumerate(toks):
        if t.kind != "p":
            continue
        if t.text in OPEN:
            stack.append(i)
        elif t.text in closer:
            for d in range(len(stack) - 1, -1, -1):
                if toks[stack[d]].text == closer[t.text]:
                    pair[stack[d]], pair[i] = i, stack[d]
                    del stack[d:]
                    break
    return pair


class Decl:
    """Something a file declares, emitted in its header.

    strong holds the names it needs fully defined before it; it only needs
    the rest declared, which a forward declaration does for a class. ahead is
    how its own file's editor context declares it before the file, if it can.
    """

    def __init__(self, f, kind, names, ns, private, start):
        self.f, self.kind, self.names, self.ns, self.private = f, kind, names, ns, private
        self.start, self.order = start, (f.index, start)
        self.text = self.fwd = self.sig = self.span = self.key = self.ahead = None
        self.target = None      # the namespace a namespace alias or using-directive names, as a tuple
        self.decl_only = None   # a declaration without the definition, for an editor context that can't have it
        self.calls = frozenset()    # its by-value names as written, qualified (`Config::compute`)
        self.constant = False   # a constexpr/consteval function: using it in a constant needs its callees too
        self.member_of = None   # for a member defined outside its class (kept whole), the class
        # A definition whose body may reach any class (through what it calls), so it goes after every class,
        # in the file's .inline.h; its declaration (if it needs one) stays in order with the rest.
        self.late = False
        self.names_only = False     # a using-declaration: another name for something declared elsewhere
        self.plain = None   # its declaration without default arguments, for its own file's editor context
        self.declared = False   # a definition with a separate declaration: what uses it only needs that
        self.body_refs = frozenset()    # names its body uses, for the start-up order of globals
        self.cond = ()          # the `#if` chains around it (see wrap)
        self.edits = ()
        self.refs = self.strong = frozenset()

    @property
    def line(self):
        return self.f.line(self.f.toks[self.start].start)


class Body:
    """A function or method definition, emitted in its file's .inl (or, with no sig, a #define or #undef
    replayed there so bodies see the macros they saw in the file)."""

    def __init__(self, f, ns, sig_line, sig, body_line, body, owner=None, refs=frozenset(), cond=()):
        self.f, self.ns, self.sig_line, self.sig, self.body_line, self.body = f, ns, sig_line, sig, body_line, body
        # What calling it looks like (`f`, `Config::compute`, `Config` for a constructor), and the names it uses
        self.owner, self.refs = (owner,) if isinstance(owner, str) else tuple(owner or ()), refs
        self.cond = cond        # the `#if` chains around it (see wrap)


class Split:
    """What moving a class's method bodies out of it produces."""

    def __init__(self):
        self.edits, self.bodies, self.posts = [], [], []
        self.weak, self.removed, self.nested = set(), set(), set()
        self.exprs = set()      # initializer and default-argument tokens
        self.members = set()    # names the class declares (methods, fields): inside it, they mean those
        self.move = True        # move method bodies out (not for class templates, which keep them)


class Parser:
    """Finds a file's top-level declarations, without a full C++ parse."""

    def __init__(self, f):
        self.f, self.src, self.toks, self.pair = f, f.text, f.toks, f.pair
        self.macros = set()     # function-like macros defined so far
        self.code_seen = False  # past the file's opening directives
        # Open `#if`s around code, at file level and in the class being read: each is its directive and
        # the #elif/#else lines since, so whatever hgen moves can be wrapped in the same conditions.
        self.cond, self.class_cond = [], []

    def cond_now(self):
        return tuple(tuple(c) for c in self.cond + self.class_cond)

    def tx(self, k):
        return self.toks[k].text if 0 <= k < len(self.toks) else ""

    def close(self, k):
        j = self.pair[k] if 0 <= k < len(self.pair) else -1
        return j if j >= 0 else len(self.toks) - 1

    def slice(self, a, b):
        return self.src[self.toks[a].start:self.toks[b].end]

    def line(self, k):
        return self.f.line(self.toks[k].start)

    def idents_at(self, ks):
        """Names used at token indices ks; `a::b::c` is recorded as "a::c"."""
        toks, out = self.toks, set()
        for k in ks:
            t = toks[k]
            if t.kind in ("num", "str"):
                m = _LITERAL_SUFFIX.search(t.text)
                if m:
                    out.add('operator""' + m.group(1))
                continue
            if t.kind != "id" or t.text in KEYWORDS or (k > 0 and toks[k - 1].text in (".", "->")):
                continue
            if k > 0 and toks[k - 1].text == "::":
                j = k - 2
                while j >= 1 and toks[j].kind == "id" and toks[j - 1].text == "::":
                    j -= 2
                head = "" if j < 0 else toks[j].text if toks[j].kind == "id" else "?" if toks[j].text == ">" else ""
                out.add(f"{head}::{t.text}")
            else:
                out.add(t.text)
        return frozenset(out)

    def idents(self, a, b):
        return self.idents_at(range(a, b + 1))

    def qualifiers(self, ks):
        """Names used as `X::member`: X must be complete there, not just declared."""
        toks = self.toks
        return frozenset(toks[k].text for k in ks if toks[k].kind == "id" and toks[k].text not in KEYWORDS
                         and self.tx(k + 1) == "::" and self.tx(k - 1) not in (".", "->", "::"))

    def by_value(self, ks):
        """Names used at ks other than through a pointer or reference."""
        return self.idents_at(k for k in ks if self.tx(k + 1) not in POINTER)

    def decl(self, kind, a, b, ns, private, names, text=None, refs=None, strong=None, ahead=None):
        d = Decl(self.f, kind, names, ns, private, a)
        d.cond = self.cond_now()
        d.text = self.slice(a, b) if text is None else text
        d.ahead = ahead
        d.refs = self.idents(a, b) if refs is None else refs
        d.strong = (d.refs if strong is None else strong) | (self.qualifiers(range(a, b + 1)) if kind != "class" else frozenset())
        self.f.decls.append(d)
        return d

    def skip_to(self, k, end):
        while k < end:
            x = self.tx(k)
            if x == ";":
                return k
            if x in OPEN:
                k = self.close(k)
            k += 1
        return end - 1

    def skip_angles(self, k, end):
        depth = 0
        while k < end:
            x = self.tx(k)
            if x in OPEN:
                k = self.close(k) + 1
                continue
            if x == "<":
                depth += 1
            elif x in (">", ">>"):
                depth -= len(x)
            if depth <= 0:
                return k + 1
            k += 1
        return end

    def skip_attrs(self, k):
        while True:
            if self.tx(k) == "[" and self.tx(k + 1) == "[":
                k = self.close(k) + 1
            elif self.tx(k) in ("alignas", "__attribute__", "__declspec") and self.tx(k + 1) == "(":
                k = self.close(k + 1) + 1
            else:
                return k

    def scope(self, i, end, ns, private):
        while i < end:
            i = self.construct(i, end, ns, private)

    def construct(self, i, end, ns, private):
        t = self.toks[i]
        if t.kind == "pp":
            return self.directive(i, end, ns, private)
        self.code_seen = self.code_seen or not ns
        if t.text == ";":
            return i + 1
        if t.text == "namespace" or (t.text == "inline" and self.tx(i + 1) == "namespace"):
            return self.namespace(i, end, ns, private)
        if t.text == "extern" and i + 1 < end and self.toks[i + 1].kind == "str":
            if self.tx(i + 2) == "{":
                c = self.close(i + 2)
                self.scope(i + 3, c, ns + ((self.slice(i, i + 1), ""),), private)
                return c + 1
            return self.declaration(i, end, ns, private, i + 2)
        if t.text in ("static_assert", "asm", "__asm__"):
            e = self.skip_to(i, end)
            self.decl("misc", i, e, ns, private, [])
            return e + 1
        if (t.kind == "id" and self.tx(i + 1) == "(" and (t.text in self.macros or _MACRO_NAME.fullmatch(t.text))
                and self.tx(self.close(i + 1) + 1) != "->"):   # `W(const char*) -> W<int>;` is a deduction guide
            k = self.close(i + 1) + 1   # a macro call such as an X-macro line
            if self.tx(k) == "{":
                k = self.close(k) + 1
            elif self.tx(k) == ";":
                k += 1
            # `MAKE_STRUCT(Point, x)` likely declares its first argument: others using Point come after it
            first = self.toks[i + 2]
            named = first.kind == "id" and first.text not in KEYWORDS and first.text not in self.macros \
                and self.tx(i + 3) in (",", ")")
            self.decl("misc", i, k - 1, ns, private, [first.text] if named else [])
            return k
        return self.declaration(i, end, ns, private)

    def directive(self, i, end, ns, private):
        """Handle a directive at file level; the ones before any code stay first, in order."""
        text = self.toks[i].text
        preamble = not ns and not self.code_seen and not self.cond
        m = _INCLUDE.match(text)
        if m:
            inc = self.f.include(m.group(1), m.group(2))
            if inc[0] == "drop":
                return i + 1
            if preamble:
                self.f.preamble.append(("include", inc, self.line(i)))
            else:
                self.f.includes.append(inc)
            return i + 1
        if _IF.match(text):
            k, depth = i + 1, 1
            while k < end and self.toks[k].kind == "pp":
                depth += 1 if _IF.match(self.tx(k)) else -1 if _ENDIF.match(self.tx(k)) else 0
                if depth == 0:
                    break
                k += 1
            if k < end and depth == 0:  # only directives inside, so it can move as a whole
                block = self.slice(i, k)
                defines = [m.group(1) for m in map(_DEFINE.match, (self.tx(j) for j in range(i, k))) if m]
                if preamble:
                    self.f.preamble.append(("text", block, self.line(i)))
                else:
                    self.f.bodies.append(Body(self.f, (), None, None, None, block, cond=self.cond_now()))
                text = "" if preamble else block
                self.decl("macro", i, k, ns, private, defines, text=text, refs=frozenset(), ahead=text)
                return k + 1
            self.cond.append([text])    # code inside: each piece is wrapped in it wherever it goes
            return i + 1
        if _ELSE.match(text):
            if self.cond:
                self.cond[-1].append(text)
            return i + 1
        if _ENDIF.match(text):
            if self.cond:
                self.cond.pop()
            return i + 1
        if _CONDITIONAL.match(text) or _PRAGMA_ONCE.match(text):
            return i + 1
        m = _DEFINE.match(text)
        if m:
            if text.startswith("(", m.end()):
                self.macros.add(m.group(1))
            body, _ = tokenize(text[m.end():])
            refs = frozenset(t.text for t in body if t.kind == "id" and t.text not in KEYWORDS)
            kept = "" if preamble else text     # a preamble #define is already at the top
            self.decl("macro", i, i, (), private, [m.group(1)], text=kept, refs=refs, ahead=kept)
            if not preamble:
                self.f.bodies.append(Body(self.f, (), None, None, None, text, cond=self.cond_now()))
        elif _UNDEF.match(text) and not preamble:
            self.decl("undef", i, i, (), private, [], text=text, refs=frozenset([_UNDEF.match(text).group(1)]))
            self.f.bodies.append(Body(self.f, (), None, None, None, text, cond=self.cond_now()))
            self.f.undefs.add(_UNDEF.match(text).group(1))
        elif not preamble:
            self.decl("misc", i, i, (), private, [], text=text, refs=frozenset())
        if preamble:
            self.f.preamble.append(("text", text, self.line(i)))
        return i + 1

    def namespace(self, i, end, ns, private):
        k = i + (2 if self.tx(i) == "inline" else 1)
        name = []
        while k < end and self.tx(k) not in ("{", "=", ";"):
            if self.tx(k) == "[":
                k = self.close(k) + 1
                continue
            name.append(self.tx(k))
            k += 1
        if self.tx(k) == "=":
            e = self.skip_to(k, end)
            d = self.decl("alias", i, e, ns, private, name[-1:], strong=frozenset(), ahead=self.slice(i, e))
            d.target = tuple(self.tx(j) for j in range(k + 1, e) if self.toks[j].kind == "id")
            self.f.namespaces.update(name[-1:])     # `alias::name` then means a name of the bot's own
            return e + 1
        if self.tx(k) != "{":
            return k + 1
        c = self.close(k)
        opener = self.src[self.toks[i].start:self.toks[k].start].strip()
        nm = "".join(name)
        self.f.namespaces.update(nm.split("::"))
        self.scope(k + 1, c, ns + ((opener, nm),), private or not nm)
        return c + 1

    def scan(self, h, end, typedef=False):
        """Find the parts of the declaration at h: parameter list, '=', ':', body and end."""
        toks = self.toks
        eq = paren = cparen = name_i = body = colon = None
        j, e = h, end - 1
        while j < end:
            x = self.tx(j)
            if (x == "<" and paren is None and eq is None and toks[j - 1].kind == "id"
                    and toks[j - 1].text not in KEYWORDS):
                # template arguments, which may call functions (`std::array<int, n()> cells`)
                k = self.skip_angles(j, end)
                if k < end and all(self.tx(m) != ";" for m in range(j, k)):
                    j = k
                    continue
            if x == "(":
                if paren is None and eq is None and not typedef:
                    ni = self.declarator_name(h, j)
                    if ni is not None:
                        paren, name_i, cparen = j, ni, self.close(j)
                        j = cparen + 1
                        continue
                j = self.close(j) + 1
                continue
            if x == "[":
                j = self.close(j) + 1
                continue
            if x == "{":
                prev = toks[j - 1]
                named = prev.kind == "id" and prev.text not in KEYWORDS
                init = typedef or eq is not None or (paren is None and (named or prev.text in ("]", ">")))
                if init or (colon is not None and (named or prev.text == ">")):
                    j = self.close(j) + 1
                    continue
                body, e = j, self.close(j)
                break
            if x == ";":
                e = j
                break
            if x == "=" and eq is None and self.tx(j - 1) != "operator":
                eq = j
            elif x == ":" and cparen is not None and eq is None and colon is None:
                colon = j
            j += 1
        return dict(eq=eq, paren=paren, cparen=cparen, name_i=name_i, body=body, e=e, colon=colon)

    def declaration(self, start, end, ns, private, h=None):
        h = start if h is None else h   # h skips an `extern "C"` that starts at start
        template = spec = False
        while self.tx(h) == "template":
            if self.tx(h + 1) != "<":       # explicit instantiation
                e = self.skip_to(h, end)
                self.decl("misc", start, e, ns, private, [])
                return e + 1
            k = self.skip_angles(h + 1, end)
            spec = spec or k == h + 3      # template<>
            template, h = True, k
        if self.tx(h) == "using":
            return self.using(start, h, end, ns, private, template)
        head = self.class_head(h, end)
        if head is not None:
            return self.class_def(start, head, end, ns, private, template, spec)
        k = self.skip_attrs(h)
        if self.tx(k) in ("class", "struct", "union", "enum"):
            e = self.skip_to(k, end)
            rest = [self.tx(j) for j in range(k + 1, e)]
            colon = rest.index(":") if ":" in rest else len(rest)    # `enum class E : std::uint8_t;`
            if rest and all(self.toks[k + 1 + j].kind == "id" or x == "::" for j, x in enumerate(rest[:colon])) \
                    and not set(rest) & {"(", "{", "=", "*", "&", "&&", ","}:
                # `class World;`: a declaration of a class defined elsewhere, written by hand; harmless as it is
                self.decl("fwddecl", start, e, ns, private, [], refs=frozenset(), strong=frozenset(),
                          ahead=self.slice(start, e))
                return e + 1
        typedef = self.tx(h) == "typedef"
        d = self.scan(h, end, typedef)
        e, paren = d["e"], d["paren"]
        if typedef:
            name = self.typedef_name(h, e)
            defines = any(self.tx(k) == "{" for k in range(h, e))   # `typedef struct {...} P;` can't be repeated
            self.decl("alias", start, e, ns, private, [name] if name else [], strong=frozenset(),
                      ahead=None if defines else self.slice(start, e))
        elif d["body"] is not None and paren is not None:
            e = self.function(start, h, d, ns, private, template, spec)
        elif d["body"] is not None:
            self.decl("misc", start, e, ns, private, [])
        elif paren is not None and not self.call_args(paren, d["cparen"]):
            self.prototype(start, h, d, ns, private, template)
        else:
            self.variable(start, h, e, ns, private, template, paren)
        return e + 1

    def declarator_name(self, h, j):
        """The index of the name a parameter list at j belongs to, if any."""
        for k in range(h, j):
            if self.tx(k) == "operator":
                return k if self.operator_end(k) == j else None
        prev = self.toks[j - 1]
        if prev.kind == "id" and prev.text not in KEYWORDS and not prev.text.startswith("__"):
            return j - 1
        return None

    def operator_end(self, k):
        n = k + 1
        x = self.tx(n)
        if x in ("(", "["):
            return self.close(n) + 1
        if x in ("new", "delete"):
            return self.close(n + 1) + 1 if self.tx(n + 1) == "[" else n + 1
        if n < len(self.toks) and self.toks[n].kind == "str":
            return n + 2 if self.toks[n + 1].kind == "id" else n + 1
        if n < len(self.toks) and self.toks[n].kind == "p":
            return n + 1
        while n < len(self.toks) and self.tx(n) not in ("(", ";", "{"):
            n += 1
        return n

    def call_args(self, paren, cparen):
        """Whether `T x(...)` has arguments (a variable) rather than parameters."""
        if cparen == paren + 1:
            return False
        for a, _, _ in self.params(paren, cparen):
            t = self.toks[a]
            if t.kind in ("num", "str") or t.text in (
                    "true", "false", "nullptr", "this", "sizeof", "new",
                    "{", "(", "-", "+", "!", "~", "&", "*"):
                return True
        return False

    def params(self, paren, cparen, angles=True):
        """(first, last, '=' or None) token indices of each parameter."""
        segs, a, k, depth, eq = [], paren + 1, paren + 1, 0, None
        while k < cparen:
            x = self.tx(k)
            if x in OPEN:
                k = self.close(k) + 1
                continue
            if angles and x == "<" and self.toks[k - 1].kind == "id":
                depth += 1
            elif angles and depth > 0 and x in (">", ">>"):
                depth -= len(x)
            elif x == "=" and eq is None and depth <= 0:
                eq = k
            elif x == "," and depth <= 0:
                segs.append((a, k - 1, eq))
                a, eq, depth = k + 1, None, 0
            k += 1
        if angles and depth > 0:
            return self.params(paren, cparen, False)
        if a < cparen:
            segs.append((a, cparen - 1, eq))
        return segs

    def signature(self, paren, cparen):
        """Parameters, default-argument token indices and parameter-name token indices."""
        segs = self.params(paren, cparen)
        defaults = {k for _, b, eq in segs if eq is not None for k in range(eq + 1, b + 1)}
        names = set()   # parameter names refer to nothing outside the function
        for a, b, eq in segs:
            k = b if eq is None else eq - 1
            if self.tx(k) == "]":
                k = self.close(k) - 1
            if k > a and self.toks[k].kind == "id" and self.tx(k - 1) != "::":
                names.add(k)
        return segs, defaults, names

    def without_defaults(self, start, paren, cparen, stop, segs):
        """The text from start to stop with default arguments removed."""
        if not any(eq is not None for _, _, eq in segs):
            return self.src[self.toks[start].start:self.toks[stop].start].rstrip()
        parts = [self.slice(a, eq - 1 if eq is not None else b).strip() for a, b, eq in segs]
        return (self.src[self.toks[start].start:self.toks[paren].end] + ", ".join(parts)
                + self.src[self.toks[cparen].start:self.toks[stop].start].rstrip())

    def qualified_name(self, name_i):
        """Whether the name at name_i is qualified (`A::f`, `A::~A`): a member defined outside its class."""
        return self.tx(name_i - 1) == "::" or (self.tx(name_i - 1) == "~" and self.tx(name_i - 2) == "::")

    def function(self, start, h, d, ns, private, template, spec):
        """A function definition; returns its last token."""
        toks = self.toks
        paren, cparen, name_i, body = d["paren"], d["cparen"], d["name_i"], d["body"]
        e = self.close(body)
        # a function-try-block: the body is `try [: inits] {...} catch (...) {...}`
        try_at = next((k for k in range(cparen + 1, body) if self.tx(k) == "try"), None)
        if try_at is not None:
            body = try_at
            while self.tx(e + 1) == "catch" and self.tx(e + 2) == "(":
                e = self.close(self.close(e + 2) + 1)
        if toks[name_i].text == "operator":
            name = "operator" + "".join(t.text for t in toks[name_i + 1:paren])
        else:
            name = toks[name_i].text
        qualified = self.qualified_name(name_i)
        specs = {t.text for t in toks[h:name_i]}
        after = {self.tx(k) for k in range(cparen + 1, body)}
        segs, _, pnames = self.signature(paren, cparen)
        ahead = self.src[toks[start].start:toks[body].start].rstrip() + ";"
        if template or spec:
            deduced = "auto" in specs and "->" not in after
            constant = bool(specs & {"constexpr", "consteval"})
            if qualified and not spec:  # a member template defined outside its class, which declares it
                d = self.decl("template", start, e, ns, private, [])
                d.late = not constant
                return e
            if spec or deduced or constant or any(self.tx(k) == "=" for k in range(start, h)):
                d = self.decl("template", start, e, ns, private, [] if qualified else [name])
                if not (spec or qualified or any(self.tx(k) == "=" for k in range(start, h))):
                    d.ahead = ahead
                return e
            # Declared where its signature allows (defaults stay there), defined after every class: its body
            # may reach any class through what it calls.
            p = self.decl("template", start, body - 1, ns, private, [name], text=ahead, ahead=ahead,
                          strong=frozenset())
            if any(eq is not None for _, _, eq in segs):
                p.plain = self.without_defaults(start, paren, cparen, body, segs) + ";"
            d = self.decl("template", start, e, ns, private, [name],
                          text=self.definition(start, h, paren, cparen, body, e, segs))
            d.late, d.body_refs = True, self.idents(body, e)
            return e
        if qualified:       # a member defined outside its class, already
            k = name_i - (2 if self.tx(name_i - 1) == "::" else 3)
            if specs & {"inline", "constexpr", "consteval"}:     # kept whole in the header, after its class
                d = self.decl("inline", start, e, ns, private, [])
                d.constant, d.member_of = bool(specs & {"constexpr", "consteval"}), self.tx(k)
                d.late = not d.constant
                return e
            ctor = self.tx(k) == name and self.tx(name_i - 1) == "::"
            self.f.bodies.append(Body(self.f, ns, self.line(start), self.src[toks[start].start:toks[body].start].rstrip(),
                                      self.line(body), self.slice(body, e),
                                      owner=[f"{self.tx(k)}::{name}"] + ([name] if ctor else []),
                                      refs=self.idents(cparen + 1, e), cond=self.cond_now()))
            return e
        private = private or "static" in specs
        deduced = "auto" in specs and "->" not in after
        if specs & {"constexpr", "consteval", "inline"} or deduced:
            # Kept whole in the header: you asked for it (inline), or it's needed in full wherever it's
            # used (constexpr), or before (deduced return type).
            constant = bool(specs & {"constexpr", "consteval"})
            if deduced:     # can't usefully be declared ahead of its definition
                d = self.decl("inline", start, e, ns, private, [name], ahead=None)
                d.decl_only, d.constant = ahead, constant
                return e
            # Declared like any function (after the types its signature uses), so these can call each other
            # in any order; defined whole once what its body needs is there. Defaults stay on the declaration.
            self.proto_decl(start, body, segs, pnames, ns, private, name, ahead, paren, cparen)
            d = self.decl("inline", start, e, ns, private, [name], text=self.definition(start, h, paren, cparen, body, e, segs))
            d.constant, d.late, d.body_refs, d.declared = constant, not constant, self.idents(body, e), True
            return e
        if name != "main":
            self.proto_decl(start, body, segs, pnames, ns, private, name, ahead, paren, cparen)
        self.f.bodies.append(Body(self.f, ns, self.line(start), self.without_defaults(start, paren, cparen, body, segs),
                                  self.line(body), self.slice(body, e), owner=name, refs=self.idents(body, e),
                                  cond=self.cond_now()))
        return e

    def definition(self, start, h, paren, cparen, body, e, segs):
        """The function at start..e as defined after its declaration: without the default arguments (and
        default template arguments) the declaration already has, its body at its own line."""
        heads, k = [], start
        while self.tx(k) == "template" and self.tx(k + 1) == "<":
            close = self.skip_angles(k + 1, body) - 1
            parts, a, depth = [], k + 2, 0
            for j in range(k + 2, close + 1):
                x = self.tx(j)
                if x in OPEN:
                    continue
                if x == "<":
                    depth += 1
                elif x in (">", ">>") and j < close:
                    depth -= len(x)
                if (x == "," and depth == 0) or j == close:
                    stop = j - 1
                    eq = next((m for m in range(a, stop + 1) if self.tx(m) == "=" and self.depth_at(a, m) == 0), None)
                    parts.append(self.src[self.toks[a].start:self.toks[(eq - 1) if eq is not None else stop].end].strip()
                                 if stop >= a else "")
                    a = j + 1
            heads.append("template <" + ", ".join(p for p in parts if p) + ">")
            k = close + 1
        rest = self.without_defaults(k, paren, cparen, body, segs)
        return " ".join(heads + [rest]) + f'\n#line {self.line(body)} "{self.f.display}"\n' + self.slice(body, e)

    def depth_at(self, a, m):
        """Angle depth at m, counting from a."""
        depth = 0
        for j in range(a, m):
            x = self.tx(j)
            depth += 1 if x == "<" else -len(x) if x in (">", ">>") else 0
        return depth

    def proto_decl(self, start, body, segs, pnames, ns, private, name, ahead, paren=None, cparen=None):
        """The declaration of the function defined at start..body: what other files see of it."""
        sig = [k for k in range(start, body) if k not in pnames]
        defaulted = [k for a, b, eq in segs if eq is not None for k in range(a, b + 1) if k not in pnames]
        p = self.decl("proto", start, body - 1, ns, private, [name],
                      text=ahead, refs=self.idents_at(sig), strong=self.idents_at(defaulted), ahead=ahead)
        if paren is not None and any(eq is not None for _, _, eq in segs):
            p.plain = self.without_defaults(start, paren, cparen, body, segs) + ";"
        p.sig = tuple(" ".join(self.tx(k) for k in range(a, (eq if eq is not None else b + 1)) if k not in pnames)
                      for a, b, eq in segs)

    def prototype(self, start, h, d, ns, private, template):
        """A function declaration the file wrote itself."""
        segs, _, pnames = self.signature(d["paren"], d["cparen"])
        name_i = d["name_i"]
        name = self.tx(name_i)
        if name == "operator":
            name = "operator" + "".join(t.text for t in self.toks[name_i + 1:d["paren"]])
        defaulted = [k for a, b, eq in segs if eq is not None for k in range(a, b + 1) if k not in pnames]
        specs = {t.text for t in self.toks[h:name_i]}
        text = self.slice(start, d["e"])
        deleted = d["eq"] is not None and self.tx(d["eq"] + 1) in ("delete", "default")   # a definition: can't repeat
        guide = name_i == h and self.tx(d["cparen"] + 1) == "->"    # `Box(T) -> Box<T>;`: can't repeat
        p = self.decl("template" if template else "proto", start, d["e"], ns, private or "static" in specs,
                      [] if self.qualified_name(name_i) else [name], text=text,
                      refs=self.idents_at(k for k in range(start, d["e"] + 1) if k not in pnames),
                      strong=self.idents_at(defaulted), ahead=None if deleted or guide else text)
        if defaulted and not (deleted or guide):
            p.plain = self.without_defaults(start, d["paren"], d["cparen"], d["e"], segs) + ";"

    def declarators(self, h, e, init_paren=None):
        """For `T a = 1, *b;` at h..e-1: the names declared, the first name's index,
        the indices before it (specifiers and type), and each initializer's range."""
        toks = self.toks
        names, inits, top = [], [], []
        first = last = None
        named, angle, k = False, 0, h

        def take():
            nonlocal first, named
            if not named and last is not None:
                names.append(toks[last].text)
                first = last if first is None else first
            named = True

        while k < e:
            x = toks[k].text
            if k == init_paren or x == "{" or (x == "=" and angle == 0):
                take()
                a = k
                if x == "=":
                    k += 1
                    while k < e and self.tx(k) != ",":
                        k = self.close(k) + 1 if self.tx(k) in OPEN else k + 1
                else:
                    k = self.close(k) + 1
                inits.append((a, k - 1))
                continue
            if first is None and angle == 0:
                top.append(k)
            if x in ("(", "["):
                k = self.close(k) + 1
                continue
            if x == "," and angle == 0:
                take()
                named = False
            elif x == "<" and k > h and toks[k - 1].kind == "id":
                angle += 1
            elif x in (">", ">>") and angle:
                angle = max(0, angle - len(x))
            elif angle == 0 and toks[k].kind == "id" and x not in KEYWORDS and not x.startswith("__"):
                last = k
            k += 1
        take()
        return names, first, [k for k in top if first is None or k < first], inits

    def strong_refs(self, ks, exprs):
        """Names at ks used by value: in a type, `T*` only needs T declared; in an expression (exprs), `a * b` uses a."""
        ks = list(ks)
        return self.by_value(k for k in ks if k not in exprs) | self.idents_at(k for k in ks if k in exprs)

    def variable(self, start, h, e, ns, private, template, init_paren):
        names, first, top, inits = self.declarators(h, e, init_paren)
        if first is not None and self.tx(first - 1) == "::":
            names = []      # a static member defined outside its class
            self.f.static_defs.add(f"{self.tx(first - 2)}::{self.tx(first)}")
        specs = {self.tx(k) for k in top}
        private = private or "static" in specs
        exprs = {k for a, b in inits for k in range(a, b + 1)}
        d = self.decl("template" if template else "var", start, e, ns, private, names,
                      strong=None if template else self.strong_refs(range(start, e + 1), exprs))
        pointer = any(self.tx(k) in POINTER for k in top)
        const = "constexpr" in specs or ("const" in specs and (not pointer or first is None or self.tx(first - 1) == "const"))
        if "extern" in specs:
            d.ahead = d.text
        elif names and not (template or private or const or specs & {"inline", "auto"}) and start == h:
            kept, k = [], h
            for a, b in inits + [(e, e)]:
                if k < a:
                    kept.append(self.slice(k, a - 1))
                k = b + 1
            d.ahead = "extern " + "".join(kept).strip() + ";"
        elif (len(names) == 1 and const and not (template or private or pointer or specs & {"auto", "static"})
              and start == h):
            # A constant declared ahead (enough for uses outside constant expressions): `extern const int N;`
            top_set = set(top)
            typ = " ".join(self.tx(k) for k in range(h, first)
                           if not (k in top_set and self.tx(k) in ("constexpr", "constinit", "const", "inline")))
            stop = inits[0][0] if inits else e
            d.ahead = f"extern const {typ} {names[0]}{self.src[self.toks[first].end:self.toks[stop].start].strip()};"
        d.decl_only = d.ahead

    def using(self, start, h, end, ns, private, template):
        e = self.skip_to(h, end)
        if self.tx(h + 1) == "namespace":
            d = self.decl("usingdir", start, e, ns, private, [], strong=frozenset(), ahead=self.slice(start, e))
            d.target = tuple(self.tx(j) for j in range(h + 2, e) if self.toks[j].kind == "id")
            self.f.using_dirs.append((self.line(start), self.slice(start, e)))
        elif self.tx(h + 1) == "enum":      # `using enum E;` needs E complete
            self.decl("usingdir", start, e, ns, private, [], ahead=self.slice(start, e))
        elif self.toks[h + 1].kind == "id" and self.tx(h + 2) == "=":
            self.decl("template" if template else "alias", start, e, ns, private, [self.tx(h + 1)],
                      strong=None if template else frozenset(), ahead=None if template else self.slice(start, e))
        else:
            names, last = [], None
            for k in range(h + 1, e + 1):
                if self.tx(k) in (",", ";") and last:
                    names.append(last)
                elif self.toks[k].kind == "id" and self.tx(k) not in KEYWORDS:
                    last = self.tx(k)
            # a using-declaration (`using geo::dot;`) needs what it names declared; it defines nothing new
            self.decl("alias", start, e, ns, private, names, ahead=self.slice(start, e)).names_only = True
        return e + 1

    def typedef_name(self, h, e):
        last, k, angle = None, h + 1, 0
        while k < e:
            x = self.tx(k)
            if x == "(":
                c = self.close(k)
                inner = [t.text for t in self.toks[k + 1:c] if t.kind == "id" and t.text not in KEYWORDS]
                if self.tx(k + 1) in ("*", "&") and inner:
                    return inner[-1]
                k = c + 1
                continue
            if x in ("[", "{"):
                k = self.close(k) + 1
                continue
            if x == "<" and self.toks[k - 1].kind == "id":
                angle += 1
            elif x in (">", ">>") and angle:
                angle = max(0, angle - len(x))
            elif angle == 0 and self.toks[k].kind == "id" and x not in KEYWORDS:
                last = x
            k += 1
        return last

    def class_head(self, h, end):
        """Return details if a class, struct, union or enum is defined at h."""
        k = self.skip_attrs(h)
        key = self.tx(k)
        if key not in ("class", "struct", "union", "enum"):
            return None
        key_start, k = k, k + 1
        scoped = key == "enum" and self.tx(k) in ("class", "struct")
        if scoped:
            k += 1
        keyword = " ".join(t.text for t in self.toks[key_start:k])
        k = self.skip_attrs(k)
        name, qualified, spec_args = None, False, None
        if k < end and self.toks[k].kind == "id" and self.tx(k) not in KEYWORDS:
            name, k = self.tx(k), k + 1
            while self.tx(k) == "::":
                qualified, name, k = True, self.tx(k + 1), k + 2
            if self.tx(k) == "<":
                a, k = k, self.skip_angles(k, end)
                spec_args = (a, k - 1)
        if self.tx(k) == "final":
            k += 1
        if self.tx(k) not in ("{", ":"):
            return None
        fixed = None
        if self.tx(k) == ":":
            b = k + 1
            while k < end and self.tx(k) != "{":
                if self.tx(k) == ";":
                    return None
                k = self.close(k) + 1 if self.tx(k) in ("(", "[") else k + 1
            if key == "enum":
                fixed = self.slice(b, k - 1).strip()
        if self.tx(k) != "{":
            return None
        return dict(keyword=keyword, name=name, qualified=qualified, spec_args=spec_args,
                    brace=k, enum=key == "enum", scoped=scoped, fixed=fixed)

    def missing_semi(self, c, end):
        """Whether the class closing at c was left without its `;` (Java has none): what follows,
        on a later line, starts another declaration rather than declaring variables of the class."""
        k = c + 1
        if k >= end or self.tx(k) == "}":
            return True
        if self.tx(k) == ";" or self.line(k) == self.line(c):
            return False
        t = self.toks[k]
        return (t.kind == "pp" or t.text in DECL_START or t.text == "~" or (t.text == "[" and self.tx(k + 1) == "[")
                or (t.kind == "id" and (self.toks[k + 1].kind == "id" or self.tx(k + 1) in ("::", "<", "*", "&", "&&"))))

    def semi_note(self, c, name):
        self.f.notes[f"{self.f.display}:{self.line(c)}: `{name or 'the class'}` needs a `;` after its closing brace "
                      f"(hgen added it)"] = None

    def class_def(self, start, head, end, ns, private, template, spec):
        brace = head["brace"]
        c = self.close(brace)
        semi = self.missing_semi(c, end)
        e = c if semi else self.skip_to(c + 1, end)
        name = head["name"]
        if semi:
            self.semi_note(c, name)
        special = template or spec or head["qualified"] or head["spec_args"] is not None
        names = [name] if name and not (head["qualified"] or head["spec_args"]) else []
        if head["enum"] and not head["scoped"]:
            names += self.enumerators(brace, c)
        if c + 1 < e:       # variables declared with it: `struct P {...} origin, unit{1, 1};`
            names += self.declarators(c + 1, e)[0]
        if special or head["enum"] or not name:
            text, strong = self.slice(start, e), None
            if not head["enum"]:    # templates keep their methods, but get nested types declared first and inline statics
                out = Split()
                out.move = False
                self.split_members(brace, c, [name or ""], ns, out, "private" if head["keyword"] == "class" else "public")
                text = self.apply(start, e, out.edits)
                strong = self.strong_refs((k for k in range(start, e + 1) if k not in out.weak), out.exprs)
            refs = None
            if strong is not None:
                own = out.members | out.nested
                strong = (strong | self.qualifiers(range(start, e + 1))) - own
                refs = self.idents(start, e) - own
            d = self.decl("class", start, e, ns, private, names, text=text + (";" if semi else ""), refs=refs, strong=strong)
            if head["enum"] and name and (head["scoped"] or head["fixed"]):
                d.fwd = f"{head['keyword']} {name}" + (f" : {head['fixed']};" if head["fixed"] else ";")
            elif (template and not spec and names and not head["qualified"] and head["spec_args"] is None
                  and not any(self.tx(k) == "=" for k in range(start, head["brace"]))):
                # `template <class T> class Box;`: a primary template without default arguments (they can't be repeated)
                key = start
                while self.tx(key) == "template":
                    key = self.skip_angles(key + 1, end)
                key = self.skip_attrs(key)
                d.fwd = f"{self.src[self.toks[start].start:self.toks[key].start].strip()} {self.tx(key)} {name};"
            return e + 1
        out = Split()
        self.split_members(brace, c, [name], ns, out, "private" if head["keyword"] == "class" else "public")
        keep = [k for k in range(start, e + 1) if k not in out.removed]
        own = out.members | out.nested     # inside the class, its own members and types
        d = self.decl("class", start, e, ns, private, names, text=self.apply(start, e, out.edits) + (";" if semi else ""),
                      refs=self.idents_at(keep) - own,
                      strong=(self.strong_refs((k for k in keep if k not in out.weak), out.exprs) | self.qualifiers(keep)) - own)
        d.fwd = f"{head['keyword']} {name};"
        d.span, d.edits = (start, e), out.edits
        for text, a, b, key, cond in out.posts:
            d = self.decl("post", a, b, ns, private, [], text=text)
            d.key, d.cond = key, cond
        self.f.bodies.extend(out.bodies)
        return e + 1

    def apply(self, a, b, edits):
        """Source text from token a to b with (first, last, replacement) token edits made."""
        out, pos = [], self.toks[a].start
        for s, t, rep, _ in sorted(edits, key=lambda ed: ed[0]):
            out.append(self.src[pos:self.toks[s].start])
            out.append(rep)
            pos = self.toks[t].end
        out.append(self.src[pos:self.toks[b].end])
        return "".join(out)

    def nested_names(self, brace, c):
        """Names of the types declared directly in the class at brace..c, wherever they are in it."""
        names, k = set(), brace + 1
        while k < c:
            x = self.tx(k)
            if x in OPEN:
                k = self.close(k) + 1
                continue
            if x in ("class", "struct", "union", "enum") and self.tx(k - 1) not in ("friend", "enum"):
                head = self.class_head(k, c)
                if head and head["name"] and not head["qualified"]:
                    names.add(head["name"])
                elif self.toks[k + 1].kind == "id" and self.tx(k + 2) == ";":
                    names.add(self.tx(k + 1))   # `class Secret;`, defined later
            elif x == "using" and self.toks[k + 1].kind == "id" and self.tx(k + 2) == "=":
                names.add(self.tx(k + 1))
            elif x == "typedef":
                names.add(self.typedef_name(k, self.skip_to(k, c)))
            k += 1
        return names

    def split_members(self, brace, c, quals, ns, out, access):
        """Move the method bodies in the class at brace..c out of it, recording edits in out."""
        k, default, fwds = brace + 1, access, []
        out.nested |= self.nested_names(brace, c)
        depth = len(self.class_cond)
        while k < c:
            t = self.toks[k]
            if t.kind == "pp":
                if _IF.match(t.text):
                    self.class_cond.append([t.text])
                elif _ELSE.match(t.text) and len(self.class_cond) > depth:
                    self.class_cond[-1].append(t.text)
                elif _ENDIF.match(t.text) and len(self.class_cond) > depth:
                    self.class_cond.pop()
                k += 1
            elif t.text in ("public", "private", "protected") and self.tx(k + 1) == ":":
                access = t.text
                k += 2
            elif t.text == ";":
                k += 1
            else:
                fwd = self.nested_fwd(k, c)
                if fwd:
                    fwds.append((access, fwd))
                k = self.member(k, c, quals, ns, out)
        if len(self.class_cond) > depth:
            self.f.notes[f"{self.f.display}:{self.line(c)}: an `#if` in this class has no `#endif` before its end"] = None
            del self.class_cond[depth:]
        if fwds:    # on the brace's line, so line numbers stay put
            text, cur = "{", default
            for acc, fwd in fwds:
                text += (f" {acc}:" if acc != cur else "") + " " + fwd
                cur = acc
            out.edits.append((brace, brace, text + (f" {default}:" if cur != default else ""), None))

    def nested_fwd(self, k, c):
        """A forward declaration of the nested class or enum defined at k, if it can have one."""
        head = self.class_head(k, c)
        if head is None or not head["name"] or head["qualified"] or head["spec_args"] is not None:
            return None
        if head["enum"] and not (head["scoped"] or head["fixed"]):
            return None     # a plain enum without a fixed type can't be declared ahead
        return f"{head['keyword']} {head['name']}" + (f" : {head['fixed']}" if head["fixed"] else "") + ";"

    def member(self, start, c, quals, ns, out):
        h = start
        if self.tx(h) == "template" and self.tx(h + 1) == "<":    # member templates stay put
            while self.tx(h) == "template" and self.tx(h + 1) == "<":
                h = self.skip_angles(h + 1, c)
            e = self.scan(h, c)["e"]
            if self.tx(h) == "friend":      # `template <class U> friend class Peeker;` needs nothing
                out.weak.update(range(start, e + 1))
            return e + 1
        if self.tx(h) in ("using", "typedef", "static_assert"):
            e = self.skip_to(h, c)
            if self.tx(h) == "typedef":
                out.nested.add(self.typedef_name(h, e))
            elif self.toks[h + 1].kind == "id" and self.tx(h + 2) == "=":
                out.nested.add(self.tx(h + 1))
            return e + 1
        head = self.class_head(h, c)
        if head is not None:
            brace = head["brace"]
            inner = self.close(brace)
            e = self.skip_to(inner + 1, c)
            if self.missing_semi(inner, c):
                e = inner
                out.edits.append((inner, inner, "};", None))
                self.semi_note(inner, head["name"])
            if head["name"]:
                out.nested.add(head["name"])
            if not head["enum"] and head["name"] and not head["qualified"] and head["spec_args"] is None:
                self.split_members(brace, inner, quals + [head["name"]], ns, out,
                                   "private" if head["keyword"] == "class" else "public")
            return e + 1
        d = self.scan(h, c)
        e = d["e"]
        if d["body"] is not None and d["paren"] is not None:
            return self.method(start, d, quals, ns, out)
        if d["paren"] is not None:      # a method declaration, maybe `= default`
            out.members.add(self.tx(d["name_i"]))
            _, defaults, _ = self.signature(d["paren"], d["cparen"])
            out.weak.update(k for k in range(start, e + 1) if k not in defaults)
            out.exprs.update(defaults)
        elif self.tx(start) == "friend":
            out.weak.update(range(start, e + 1))
        else:
            self.data_member(start, e, quals, out)
        return e + 1

    def data_member(self, start, e, quals, out):
        """Static data members need `inline` (or a definition outside the class) to just work."""
        toks = self.toks
        names, first, top, inits = self.declarators(start, e)
        out.members.update(names)
        out.exprs.update(k for a, b in inits for k in range(a, b + 1))
        static = next((k for k in top if self.tx(k) == "static"), None)
        specs = {self.tx(k) for k in top}
        if static is None or not names or specs & {"constexpr", "inline"}:
            return
        key = f"{quals[-1]}::{names[0]}"
        # A static of the class's own type (`static Foo origin;`, `static std::vector<Foo> all;`) or of a type
        # declared in it (maybe further down, Java style) can't be defined inside the class: it's defined after.
        if len(names) > 1 or not {self.tx(k) for k in range(start, first)} & (set(quals) | out.nested):
            out.edits.append((static, static, "inline static", key))
            return
        if not out.move:
            return      # a class template's: left as written
        init = ""
        if inits:
            a, b = inits[0]
            init = self.slice(a, b)
            out.edits.append((a, b, "\n" * init.count("\n"), key))
        init = (" " + init) if init.startswith("=") else init
        q = "::".join(quals)
        out.posts.append((f"decltype({q}::{names[0]}) {q}::{names[0]}{init};", start, e, key, self.cond_now()))

    def method(self, start, d, quals, ns, out):
        toks = self.toks
        paren, cparen, name_i, body, colon = d["paren"], d["cparen"], d["name_i"], d["body"], d["colon"]
        out.members.add(self.tx(name_i))
        e = self.close(body)
        name_start = name_i - 1 if self.tx(name_i - 1) == "~" else name_i
        specs = {t.text for t in toks[start:name_start]}
        head_end = colon if colon is not None else body
        after = [self.tx(k) for k in range(cparen + 1, head_end)]
        try_block = "try" in after or self.tx(body - 1) == "try"   # `A() try : v(f()) {} catch (...) {}` too
        if try_block:
            while self.tx(e + 1) == "catch" and self.tx(e + 2) == "(":
                e = self.close(self.close(e + 2) + 1)
        if not out.move:
            return e + 1
        if (specs & {"constexpr", "consteval", "inline"} or ("auto" in specs and "->" not in after)
                or "requires" in after or try_block or self.tx(name_start - 1) == "::"):
            return e + 1    # stays in the class: you asked for it (inline), or it's needed in full where it's used
        segs, defaults, _ = self.signature(paren, cparen)
        out.weak.update(k for k in range(start, head_end) if k not in defaults)
        out.exprs.update(defaults)
        out.removed.update(range(head_end, e + 1))
        decl = self.src[toks[start].start:toks[head_end].start].rstrip() + ";"
        gone = self.src[toks[head_end].start:toks[e].end]
        out.edits.append((start, e, decl + "\n" * gone.count("\n"), None))

        ret_start = start
        while ret_start < name_start:
            x = self.tx(ret_start)
            if x == "[" and self.tx(ret_start + 1) == "[":
                ret_start = self.close(ret_start) + 1
            elif x == "explicit" and self.tx(ret_start + 1) == "(":
                ret_start = self.close(ret_start + 1) + 1
            elif x in MEMBER_ONLY:
                ret_start += 1
            else:
                break
        ret = self.src[toks[ret_start].start:toks[name_start].start].strip() if ret_start < name_start else ""
        name = self.src[toks[name_start].start:toks[paren].start].strip()
        params = self.without_defaults(paren, paren, cparen, cparen + 1, segs)
        qualifiers = _OVERRIDE.sub("", self.src[toks[cparen].end:toks[head_end].start]).rstrip()
        if "friend" in specs:       # a friend is a free function, not a member
            sig = f"{ret} {name}{params}{qualifiers}"
        else:
            name = "::".join(quals) + "::" + name
            if ret and "->" not in after and self.idents(ret_start, name_start - 1) & out.nested:
                sig = f"auto {name}{params}{qualifiers} -> {ret}"   # so nested types resolve
            else:
                sig = f"{ret} {name}{params}{qualifiers}".lstrip()
        if colon is not None:
            sig += " " + self.src[toks[colon].start:toks[body].start].strip()
        ctor = self.tx(name_start) == quals[-1]   # a constructor runs when a global of its class starts up
        out.bodies.append(Body(self.f, ns, self.line(start), sig, self.line(body), self.slice(body, e),
                               owner=[f"{quals[-1]}::{self.tx(name_i)}"] + ([quals[-1]] if ctor else []),
                               refs=self.idents(cparen + 1, e), cond=self.cond_now()))
        return e + 1

    def enumerators(self, brace, c):
        names, k, expect = [], brace + 1, True
        while k < c:
            x = self.tx(k)
            if x in OPEN:
                k = self.close(k) + 1
                continue
            if expect and self.toks[k].kind == "id":
                names.append(x)
                expect = False
            elif x == ",":
                expect = True
            k += 1
        return names


class SrcFile:
    def __init__(self, bot, path, index):
        self.bot, self.path, self.index = bot, path, index
        self.rel = path.relative_to(bot.dir).as_posix()
        self.display = display_path(path, bot)
        stem = Path(self.rel).with_suffix("")
        self.header = bot.src / "headers" / stem.with_suffix(".h")
        self.late_header = bot.src / "headers" / stem.with_suffix(".inline.h")
        self.inl = bot.src / stem.with_suffix(".inl")
        self.text = read(path)
        self.toks, self.comments = tokenize(self.text)
        self.toks = Toks(drop_disabled(self.toks), len(self.text))
        self.comment_ends = [e for _, e in self.comments]
        self.pair = match_brackets(self.toks)
        self.newlines = [m.start() for m in re.finditer("\n", self.text)]
        self.preamble, self.includes, self.decls, self.bodies = [], [], [], []
        self.namespaces, self.notes, self.static_defs = set(), {}, set()
        self.using_dirs = []    # (line, text) of file-level `using namespace`
        self.undefs = set()     # macros the file #undefs after its opening directives
        self.parser = Parser(self)
        self.parser.scope(0, len(self.toks), (), False)
        if self.parser.cond:
            self.notes[f"{self.display}: an `#if` around code has no `#endif`"] = None

    def line(self, pos):
        return bisect.bisect_left(self.newlines, pos) + 1

    def include(self, style, path):
        """How to include path from src/: files in the bot folder are copied into src/."""
        if path.endswith(SOURCE):
            self.notes[f"{self.display}: #include of {path} isn't needed (every file sees what the others "
                       f"declare), so hgen leaves it out"] = None
            return ("drop", path)
        if style == '"':
            target = os.path.normpath(os.path.join(str(self.path.parent), path))
            if os.path.isfile(target):
                if within(target, self.bot.dir) and not within(target, self.bot.src):
                    target = os.path.join(str(self.bot.src), os.path.relpath(target, str(self.bot.dir)))
                else:
                    self.notes[f"{self.display}: \"{path}\" is outside the bot folder, so cambc submit "
                               f"won't upload it; move it into the bot folder"] = None
                return ("file", target)
        return (style, path)

    def directives(self, header, original=False):
        """This file's opening directives and later includes, as they go in header
        (pointing at the bot folder's own headers if original, else their copies in src/)."""
        def where(path):
            if original and within(path, self.bot.src):
                path = os.path.join(str(self.bot.dir), os.path.relpath(path, str(self.bot.src)))
            return rel_include(Path(path), header)

        def fix(m):
            style, path = self.include('"', m.group(2))
            if style == "drop":
                return f"/* {m.group(0)} */"
            return m.group(1) + (where(path) if style == "file" else path) + m.group(3)
        for kind, val, line in self.preamble + [("include", inc, 0) for inc in self.includes]:
            if kind == "include":
                style, path = val
                yield val, (f"#include <{path}>" if style == "<" else
                            f'#include "{where(path) if style == "file" else path}"')
            else:
                # Its own value even if another file's opening lines define the same macro; a problem in it
                # is reported at its own line.
                m = _DEFINE.match(val)
                yield None, (f"#undef {m.group(1)}\n" if m else "") + f'#line {line} "{self.display}"\n' \
                    + _QUOTED_INCLUDE.sub(fix, val)

    def doc(self, pos):
        """The comment block directly above pos, if any."""
        k = bisect.bisect_right(self.comment_ends, pos) - 1
        block, limit = [], pos
        while k >= 0:
            s, e = self.comments[k]
            gap = self.text[e:limit]
            if gap.strip() or gap.count("\n") > 1 or self.text[self.text.rfind("\n", 0, s) + 1:s].strip():
                break
            block.append(self.text[s:e])
            limit, k = s, k - 1
        return "\n".join(reversed(block))


def unqualify(refs, user_ns):
    """Keep `ns::name` uses only where ns is one of the bot's own namespaces."""
    out = set()
    for r in refs:
        head, sep, name = r.rpartition("::")
        if not sep:
            out.add(r)
        elif head in user_ns or not head:
            out.add(name)
    return frozenset(out)


def guarded(path):
    """Whether a header protects itself from being included twice."""
    try:
        text = read(path)
    except OSError:
        return True
    return bool(_PRAGMA_ONCE.search(text) or re.search(r"^\s*#\s*ifndef\s+(\w+)\s*\n\s*#\s*define\s+\1\b", text, re.M))


def within(path, folder):
    path, folder = os.path.abspath(str(path)), os.path.abspath(str(folder))
    return path == folder or path.startswith(folder + os.sep)


def display_path(path, bot):
    """How errors name a file: from the workspace root, as cambc runs there."""
    base = ROOT if within(path, ROOT) else bot.dir.parent
    return Path(os.path.relpath(str(path), str(base))).as_posix()


def read(path):
    """A file's text, with a byte order mark and Windows line endings (as Windows editors write) removed."""
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        text = path.read_text(encoding="latin-1")
    return (text[1:] if text.startswith("\ufeff") else text).replace("\r\n", "\n")


def is_generated(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.readline().startswith((BANNER_PREFIX,) + OLD_BANNERS)
    except OSError:
        return False


def bot_files(bot_dir, suffixes):
    """Files in the bot folder you write, sorted; src/, build output, hidden files and folders excluded
    (an editor's lock file, `.#bot.htb`, is a broken link)."""
    out = []
    for dirpath, dirnames, filenames in os.walk(str(bot_dir)):
        top = os.path.abspath(dirpath) == os.path.abspath(str(bot_dir))
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".")
                             and not (top and d in ("src", "build", "target")))
        out += [Path(dirpath) / n for n in sorted(filenames)
                if n.endswith(suffixes) and not n.startswith(".") and os.path.isfile(os.path.join(dirpath, n))]
    return out


class Bot:
    def __init__(self, path):
        self.dir, self.name, self.src = path, path.name, path / "src"
        self.files = [SrcFile(self, p, i) for i, p in enumerate(bot_files(path, (SOURCE,)))]
        # A header of yours where hgen would write one keeps its place (names compared ignoring case,
        # as macOS and Windows do).
        copied = {str(self.src / p.relative_to(self.dir)).lower() for p in bot_files(path, HEADER_TYPES)}
        for f in self.files:
            if str(f.header).lower() in copied:
                f.header = f.header.with_name(f.header.stem + ".htb.h")
            if str(f.inl).lower() in copied:
                f.inl = f.inl.with_name(f.inl.stem + ".htb.inl")
            if str(f.late_header).lower() in copied:
                f.late_header = f.late_header.with_name(f.late_header.name.replace(".inline.h", ".htb.inline.h"))
        user_ns = {n for f in self.files for n in f.namespaces if n}
        # Static members someone defined outside their class keep their plain declaration.
        defined = {key for f in self.files for key in f.static_defs}
        for f in self.files:
            f.decls = [d for d in f.decls if d.key not in defined]
            for d in f.decls:
                if any(ed[3] in defined for ed in d.edits):
                    d.text = f.parser.apply(*d.span, [ed for ed in d.edits if ed[3] not in defined])
            for d in f.decls:
                d.calls = d.strong      # as written (`Config::compute`), for the start-up order of globals
                d.refs, d.strong = unqualify(d.refs, user_ns), unqualify(d.strong, user_ns)
                # Its own name inside it (constructors, `Node* next`, `int x = 5;` beside an `extern int x;`)
                # means itself or another declaration of it, never something to put first.
                # (a using-declaration's one name is what it brings in, though)
                if d.kind in ("class", "var", "proto", "inline") or (d.kind == "alias" and not d.names_only):
                    d.refs, d.strong = d.refs - set(d.names), d.strong - set(d.names)

    def init_reads(self, d, resolve):
        """The globals a global's initializer reads through the functions (and constructors) it calls:
        they must start up first, as they would in Java."""
        if not hasattr(self, "body_refs"):
            self.body_refs = defaultdict(set)
            for f in self.files:
                for b in f.bodies:
                    for key in b.owner:
                        self.body_refs[key] |= b.refs
                for x in f.decls:
                    for key in x.names:
                        self.body_refs[key] |= x.body_refs
        seen, todo, out = set(), list(d.strong | d.calls), set()
        while todo:
            r = todo.pop()
            if r in seen:
                continue
            seen.add(r)
            todo += self.body_refs.get(r, ())
            # (another declaration of the same global, `extern int x;` beside `int x = 5;`, isn't a different one)
            out.update(x for x in resolve(r.rpartition("::")[2], d.f)
                       if x.kind == "var" and x is not d and not set(x.names) & set(d.names))
        return out

    def context_path(self, f):
        return self.dir / CONTEXT_DIR / Path(f.rel).with_suffix(".h")

    def generate(self):
        """Return ({src/ path: text}, [notes], {editor context path: text})."""
        notes = {}
        for p in bot_files(self.dir, (".cpp", ".cc", ".cxx", ".c++")):
            notes[f"{display_path(p, self)} isn't part of the build (cambc builds src/, which hgen writes from the "
                  f".htb files): rename it to .htb"] = None
        for f in self.files:
            notes.update(f.notes)
            for line, text in f.using_dirs if len(self.files) > 1 else ():
                notes[f"{f.display}:{line}: `{text}` reaches every file of the bot (they're compiled as one), so a "
                      f"name it brings in can clash with one in another file; `std::name` or `using std::name;` "
                      f"for just the names you need avoids that"] = None
        decls = [d for f in self.files for d in f.decls]
        by_name = defaultdict(list)
        for d in decls:
            for n in d.names:
                by_name[n].append(d)

        def resolve(name, f):
            return [d for d in by_name.get(name, ()) if not d.private or d.f is f]

        def aliased(x, seen):
            """What an alias (typedef, using) names, through other aliases."""
            for r in x.refs:
                for y in resolve(r, x.f):
                    if y not in seen:
                        seen.add(y)
                        yield y
                        if y.kind == "alias":
                            yield from aliased(y, seen)

        def ns_path(d):
            return tuple(p for _, nm in d.ns for p in nm.split("::") if p)

        def within_ns(x, target):
            path = ns_path(x)
            return any(path[i:i + len(target)] == target for i in range(len(path) - len(target) + 1))

        # What each declaration needs defined before it.
        deps = {d: set() for d in decls}
        for d in decls:
            if d.kind == "macro":
                continue    # a macro needs nothing until it's used
            if d.target:    # `namespace gm = geo::metrics;`, `using namespace geo;`: geo's contents first
                deps[d].update(x for x in decls if x is not d and x.kind != "usingdir" and within_ns(x, d.target))
            for r in d.refs:
                for x in resolve(r, d.f):
                    # Only what r must be complete for counts: a class can be forward-declared,
                    # and a function or global matters only in an initializer or default argument.
                    if x is not d and (r in d.strong or not (x.fwd or x.kind in ("proto", "var"))):
                        deps[d].add(x)
                        if x.kind == "alias" and r in d.strong:
                            deps[d].update(y for y in aliased(x, {x, d}))
            deps[d].update(x for x in d.f.decls if x.kind == "usingdir" and x.order < d.order)
            if d.kind == "undef":
                deps[d].update(x for x in d.f.decls if x is not d and d.refs & x.refs)
            if d.kind == "var":
                deps[d].update(self.init_reads(d, resolve))
        # Late definitions come after every class anyway; what's in order only needs their declarations.
        for d in decls:
            if not d.late:
                deps[d] = {x for x in deps[d] if not x.late}
        # Whatever needs a class comes after its constexpr members defined outside it: evaluating one needs it.
        member_defs = defaultdict(list)
        for d in decls:
            if d.member_of and d.constant:
                member_defs[d.member_of].append(d)
        for d in decls if member_defs else ():
            for x in list(deps[d]):
                if x.kind == "class" and x.names and d.member_of != x.names[0]:
                    deps[d].update(m for m in member_defs.get(x.names[0], ()) if m is not d)
        # Evaluating a constexpr function needs every constexpr function it calls defined, too.
        for d in decls:
            todo = [x for x in deps[d] if x.constant]
            seen = set(todo)
            while todo:
                for y in deps[todo.pop()]:
                    if y.constant and y not in seen and y is not d:
                        seen.add(y)
                        todo.append(y)
            deps[d] |= seen
        self.clashes(by_name, notes)

        # Files whose declarations need each other's share one header.
        needs = {f: set() for f in self.files}
        for d in decls:
            needs[d.f].update(x.f for x in deps[d] if x.f is not d.f)
        groups = file_groups(self.files, needs)
        group_of = {f: g for g in groups for f in g}

        out, emission = {}, []
        late_headers = []
        for g in groups:
            owner = g[0]
            ordered = topo_sort([d for f in g for d in f.decls], deps)
            items, late = [d for d in ordered if not d.late], [d for d in ordered if d.late]
            emission += items
            used = {g2[0] for f in g for n in needs[f] for g2 in [group_of[n]] if g2 is not g}
            out[owner.header] = header_text(owner, g, items, sorted(used, key=lambda f: f.index), resolve)
            if late:
                out[owner.late_header] = late_text(g, late)
                late_headers.append(owner.late_header)
            for f in g[1:]:
                out[f.header] = (f"{BANNER_PREFIX} from {f.rel}. {EDIT_HINT.format(src=f.rel)}\n"
                                 f"// {f.rel} and {owner.rel} need each other's declarations, so all of "
                                 f"them are in {owner.header.name}.\n#pragma once\n"
                                 f'#include "{rel_include(owner.header, f.header)}"\n')
        for f in self.files:
            out[f.inl] = inl_text(f)
        unity = self.src / "unity.cpp"
        lines = [f"{BANNER_PREFIX}. Do not edit: change the bot's {SOURCE} files and run tools/htb/hgen.py.",
                 "// The whole bot as one translation unit: every file's declarations, then every",
                 "// file's function bodies, so the compiler can inline calls across files.", ""]
        # Each file sees the library headers any file includes, as the editor shows it.
        system = [f"#include <{val[1]}>" for f in self.files for kind, val, _ in f.preamble + [("include", i, 0) for i in f.includes]
                  if kind == "include" and val[0] == "<"]
        lines += list(dict.fromkeys(system)) + [""] if system else []
        lines += [f'#include "{rel_include(f.header, unity)}"' for g in groups for f in g]
        lines += [f'#include "{rel_include(h, unity)}"' for h in late_headers]   # after every class
        lines.append("")
        lines += [f'#include "{rel_include(f.inl, unity)}"' for f in self.files]
        out[unity] = "\n".join(lines) + "\n"
        for path in bot_files(self.dir, HEADER_TYPES):
            rel = path.relative_to(self.dir).as_posix()
            # `#pragma once`: the bot is one unit, so a header without a guard would be included twice
            out[self.src / rel] = (f"{BANNER_PREFIX}: a copy of {rel}. {EDIT_HINT.format(src=rel)}\n#pragma once\n"
                                   f'#line 1 "{display_path(path, self)}"\n' + read(path))
        contexts = {self.context_path(f): self.context_text(f, emission, deps) for f in self.files}
        return out, list(notes), contexts

    def context_text(self, X, emission, deps):
        """What X uses from the other files, for an editor to read before X itself."""
        path = self.context_path(X)
        lines = [f"{BANNER_PREFIX} for editors: read before {X.rel}, so clangd knows what the bot's",
                 "// other files declare. cambc never compiles this; it builds src/unity.cpp.", "#pragma once", ""]
        # A header without an include guard that X includes itself would be read twice: leave it to X.
        seen = {inc for inc, _ in X.directives(path, original=True) if inc and inc[0] == "file"
                and not guarded(self.dir / os.path.relpath(inc[1], str(self.src)) if within(inc[1], self.src) else Path(inc[1]))}
        for f in [X] + [f for f in self.files if f is not X]:
            for inc, text in f.directives(path, original=True):
                if inc is None or inc not in seen:
                    seen.add(inc)
                    lines.append(text)
        lines.append("")
        emit(lines, [(d.ns, d.fwd) for d in sorted(emission, key=lambda d: d.order) if d.fwd])
        lines.append("")
        # X's own declarations come later, in X itself; so must whatever needs them.
        blocked, blocks = {d for d in X.decls if d.ahead is None and not d.declared}, []
        # X repeats its own functions' default arguments where it defines them: declared ahead with them too,
        # clang reports a redefinition, and its recovery can make later calls ambiguous. So X's own come
        # without defaults, unless X calls one before its definition (Java order needs them there).
        first_call = {}
        for k, t in enumerate(X.toks):
            if t.kind == "id" and X.toks[k + 1].text == "(":
                first_call.setdefault(t.text, k)
        for d in emission:
            if d.late:
                continue
            if d in blocked or any(x in blocked for x in deps[d]):
                blocked.add(d)
                if d.f is not X and d.decl_only:    # e.g. `extern const int SCALE;`: usable, if not in full
                    blocks.append((d.ns, wrap(d.cond, f'#line {d.line} "{d.f.display}"\n{d.decl_only}\n')))
                continue
            text = d.ahead if d.f is X else d.text
            if d.f is X and d.plain and first_call.get(d.names[0] if d.names else "", len(X.toks)) >= d.start:
                # (a template can't gain default arguments after it's declared: X's own is left to X)
                text = d.plain if d.kind != "template" else ""
            if text:
                doc = d.f.doc(d.f.toks[d.start].start)
                # The #line lets the HTB extension send go to definition from here to the .htb line.
                blocks.append((d.ns, wrap(d.cond, (doc + "\n" if doc else "") + f'#line {d.line} "{d.f.display}"\n{text}\n')))
        emit(lines, blocks)
        return "\n".join(lines).rstrip() + "\n"

    def clashes(self, by_name, notes):
        def named(d):   # its namespaces, anonymous ones left out: those are one namespace in the bot
            return tuple(p for _, nm in d.ns for p in nm.split("::") if p)

        def related(a, b):  # one can only hide or clash with the other in the same or an enclosing namespace
            x, y = named(a), named(b)
            return x[:len(y)] == y or y[:len(x)] == x

        """A file's private things (static, anonymous namespace) are seen by every file, as everything is
        compiled together: the same name in another file clashes, or one hides the other."""
        for name, ds in sorted(by_name.items()):
            same, other = {}, {}    # per pair of files: one note, the stronger
            for i, a in enumerate(ds):
                for b in ds[i + 1:]:
                    if (a.f is b.f or not (a.private or b.private) or "fwddecl" in (a.kind, b.kind)
                            or a.names_only or b.names_only
                            or (a.kind == b.kind == "alias" and a.text.split() == b.text.split())
                            or not related(a, b)):
                        continue    # (the same alias twice, `using vec2 = cambc::vec2;`, is allowed)
                    pair = frozenset((a.f, b.f))
                    if a.kind == b.kind and a.kind in ("proto", "var") and a.sig == b.sig:
                        same.setdefault(pair, f"{a.f.display}:{a.line} and {b.f.display}:{b.line} both define "
                                              f"`{name}`; the whole bot is compiled together, so rename one")
                    else:
                        p, o = (a, b) if a.private else (b, a)
                        other.setdefault(pair, f"{p.f.display}:{p.line}: the file-private `{name}` is seen by every "
                                               f"file (the bot is compiled as one), so it can hide or clash with "
                                               f"{o.f.display}:{o.line}'s; rename one")
            for pair, note in list(other.items()):
                notes[same.pop(pair, note)] = None
            for note in same.values():
                notes[note] = None


def file_groups(files, needs):
    """Group files that need each other (strongly connected), ordered so needs come first."""
    index, low, stack, on, comps = {}, {}, [], set(), []

    def visit(v):
        index[v] = low[v] = len(index)
        stack.append(v)
        on.add(v)
        for w in sorted(needs[v], key=lambda f: f.index):
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w is v:
                    break
            comps.append(sorted(comp, key=lambda f: f.index))

    for f in files:
        if f not in index:
            visit(f)
    # Tarjan's order puts needs first; settle ties by file order.
    group_of = {f: tuple(c) for c in comps for f in c}
    after = {tuple(c): {group_of[n] for f in c for n in needs[f]} - {tuple(c)} for c in comps}
    done, ordered = set(), []
    while len(ordered) < len(comps):
        ready = [c for c in after if c not in done and after[c] <= done]
        c = min(ready or [c for c in after if c not in done], key=lambda c: c[0].index)
        done.add(c)
        ordered.append(list(c))
    return ordered


def strongly_connected(items, edges):
    """Tarjan's strongly connected components (iteratively: a long chain would overflow Python's stack)."""
    index, low, on, stack, comps, counter = {}, {}, set(), [], [], [0]
    for root in items:
        if root in index:
            continue
        work = [(root, iter(edges[root]))]
        index[root] = low[root] = counter[0]
        counter[0] += 1
        stack.append(root)
        on.add(root)
        while work:
            v, it = work[-1]
            for w in it:
                if w not in index:
                    index[w] = low[w] = counter[0]
                    counter[0] += 1
                    stack.append(w)
                    on.add(w)
                    work.append((w, iter(edges[w])))
                    break
                if w in on:
                    low[v] = min(low[v], index[w])
            else:
                work.pop()
                if work:
                    low[work[-1][0]] = min(low[work[-1][0]], low[v])
                if low[v] == index[v]:
                    comp = []
                    while True:
                        w = stack.pop()
                        on.discard(w)
                        comp.append(w)
                        if w is v:
                            break
                    comps.append(comp)
    return comps


def topo_sort(items, deps):
    """Order items so each comes after what it needs, else in source order. Only a real cycle (things
    needing each other) is broken, and only among its own members: everything else keeps its order."""
    items = sorted(items, key=lambda d: d.order)
    pos = {d: n for n, d in enumerate(items)}
    inner = {d: [x for x in deps[d] if x in pos and x is not d] for d in items}
    comps = strongly_connected(items, inner)
    comp_of = {d: i for i, c in enumerate(comps) for d in c}
    needs = {i: {comp_of[x] for d in c for x in inner[d]} - {i} for i, c in enumerate(comps)}
    users = defaultdict(list)
    for i, ns in needs.items():
        for n in ns:
            users[n].append(i)
    left = {i: len(ns) for i, ns in needs.items()}
    first = {i: min(pos[d] for d in c) for i, c in enumerate(comps)}
    ready = [(first[i], i) for i in left if not left[i]]
    heapq.heapify(ready)
    out = []
    while ready:
        _, i = heapq.heappop(ready)
        out += order_cycle(comps[i], inner, pos)
        for u in users[i]:
            left[u] -= 1
            if not left[u]:
                heapq.heappush(ready, (first[u], u))
    return out


def order_cycle(comp, inner, pos):
    """A cycle's members: what can go first does, by source order; when nothing can, the earliest goes."""
    if len(comp) == 1:
        return comp
    members = set(comp)
    left = {d: sum(1 for x in inner[d] if x in members) for d in comp}
    users = defaultdict(list)
    for d in comp:
        for x in inner[d]:
            if x in members:
                users[x].append(d)
    done, out = set(), []
    ready = [pos[d] for d in comp if not left[d]]
    heapq.heapify(ready)
    by_pos = {pos[d]: d for d in comp}
    while len(out) < len(comp):
        if not ready:
            heapq.heappush(ready, min(pos[d] for d in comp if d not in done))
        d = by_pos[heapq.heappop(ready)]
        if d in done:
            continue
        done.add(d)
        out.append(d)
        for u in users[d]:
            left[u] -= 1
            if left[u] == 0 and u not in done:
                heapq.heappush(ready, pos[u])
    return out


def rel_include(target, including):
    return Path(os.path.relpath(str(target), str(including.parent))).as_posix()


def header_text(owner, group, items, used, resolve):
    names = " and ".join(f.rel for f in group)
    lines = [f"{BANNER_PREFIX} from {names}. {EDIT_HINT.format(src=names)}", "#pragma once", ""]
    seen = set()
    for f in group:
        for inc, text in f.directives(owner.header):
            if inc is None or inc not in seen:
                seen.add(inc)
                lines.append(text)
    lines += [f'#include "{rel_include(f.header, owner.header)}"' for f in used]
    if seen or used:
        lines.append("")
    fwd = {}
    for d in items:
        for r in d.refs:
            for x in resolve(r, d.f):
                if x.fwd:
                    fwd[x] = None
    if fwd:
        emit(lines, [(x.ns, x.fwd) for x in sorted(fwd, key=lambda x: x.order)])
        lines.append("")
    blocks = []
    for d in items:
        if not d.text:
            continue    # a macro from the file's opening directives, already above
        doc = d.f.doc(d.f.toks[d.start].start)
        blocks.append((d.ns, wrap(d.cond, (doc + "\n" if doc else "") + f'#line {d.line} "{d.f.display}"\n{d.text}\n')))
    emit(lines, blocks)
    return "\n".join(lines).rstrip() + "\n"


def late_text(group, items):
    """Inline functions and templates, defined once every class is complete (their declarations come earlier)."""
    names = " and ".join(f.rel for f in group)
    lines = [f"{BANNER_PREFIX} from {names}. {EDIT_HINT.format(src=names)}",
             "// Inline functions and templates, defined after every class: src/unity.cpp includes this after",
             "// every header (the declarations are in them).", "#pragma once", ""]
    blocks = []
    for d in items:
        doc = d.f.doc(d.f.toks[d.start].start)
        blocks.append((d.ns, wrap(d.cond, (doc + "\n" if doc else "") + f'#line {d.line} "{d.f.display}"\n{d.text}\n')))
    emit(lines, blocks)
    return "\n".join(lines).rstrip() + "\n"


def inl_text(f):
    lines = [f"{BANNER_PREFIX} from {f.rel}. {EDIT_HINT.format(src=f.rel)}",
             "// Function bodies; src/unity.cpp includes this after every header.", ""]
    # Bodies see the macros they saw in the file, whatever other files define: its opening #defines
    # first, then its later #defines and #undefs in order.
    for kind, text, _ in f.preamble:
        m = _DEFINE.match(text) if kind == "text" else None
        if m:
            lines += [f"#undef {m.group(1)}", text]
    emit(lines, [(b.ns, wrap(b.cond, b.body + "\n" if b.sig is None else
                  f'#line {b.sig_line} "{f.display}"\n{b.sig}\n#line {b.body_line} "{f.display}"\n{b.body}\n'))
                 for b in f.bodies])
    return "\n".join(lines).rstrip() + "\n"


def wrap(cond, text):
    """text inside the `#if` chains it was in: for each, the #if and the #elif/#else before its branch."""
    if not cond:
        return text
    return "\n".join([line for chain in cond for line in chain] + [text.rstrip("\n")] + ["#endif"] * len(cond)) + "\n"


def emit(lines, blocks):
    """Append (namespace path, text) blocks, opening namespaces as needed."""
    cur = ()
    for ns, text in blocks:
        if ns != cur:
            lines.extend("}" for _ in cur)
            lines.extend(f"{opener} {{" for opener, _ in ns)
            cur = ns
        lines.append(text)
    lines.extend("}" for _ in cur)


def find_bots(names):
    bots_dir = ROOT / "bots"
    if names:
        found = []
        for name in names:
            path = Path(name) if Path(name).is_dir() and not (bots_dir / name).is_dir() else bots_dir / name
            if not path.is_dir():
                sys.exit(f"hgen: no bot at {name} (looked for {path})")
            if not bot_files(path, (SOURCE,)):
                sys.exit(f"hgen: {path} has no {SOURCE} files of its own; write the bot's {SOURCE} files there")
            found.append(path.resolve())
        return found
    if not bots_dir.is_dir():
        return []
    return [d.resolve() for d in sorted(bots_dir.iterdir()) if d.is_dir() and bot_files(d, (SOURCE,))]


def run(path, check=False):
    """Regenerate one bot's src/; return "ok", "stale" (it was out of date) or "refused"."""
    bot = Bot(path)
    outputs, notes, contexts = bot.generate()
    existing = [p for p in bot.src.rglob("*") if p.is_file()] if bot.src.is_dir() else []
    foreign = [p for p in existing if p not in outputs and not is_generated(p)]
    stale = [p for p in existing if p not in outputs and is_generated(p)]
    changed = [p for p, text in outputs.items() if not p.exists() or read(p) != text]
    rel = lambda p: p.relative_to(bot.dir).as_posix()
    if foreign:
        print(f"{bot.name}: left alone, because src/ has files hgen didn't write:")
        for p in foreign:
            print(f"  {rel(p)}")
        print(f"  hgen writes src/ from the {SOURCE} files in the bot folder; move these out of src/ or delete them")
        return "refused"
    if check:
        for p in changed:
            print(f"{bot.name}: {rel(p)} is out of date")
        for p in stale:
            print(f"{bot.name}: {rel(p)} is left over")
    else:
        for p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as out:
                out.write(outputs[p])
        for p in stale:
            p.unlink()
        for d in sorted(bot.src.rglob("*"), reverse=True):
            if d.is_dir() and not any(d.iterdir()):
                d.rmdir()
        write_editor_support(bot, contexts)
        done = [f"wrote {len(changed)} file{'s' * (len(changed) != 1)} in src/"] if changed else []
        done += [f"removed {', '.join(rel(p) for p in stale)}"] if stale else []
        print(f"{bot.name}: {'; '.join(done) if done else 'src/ up to date'}")
    for note in notes:
        print(f"  note: {note}")
    return "stale" if changed or stale else "ok"


def write_editor_support(bot, contexts):
    """Write each file's editor context, and point clangd at them in the bot's .clangd."""
    folder = bot.dir / CONTEXT_DIR
    for p in list(folder.rglob("*.h")) if folder.is_dir() else []:
        if p not in contexts:
            p.unlink()
    for p, text in contexts.items():
        if not p.exists() or read(p) != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "w", encoding="utf-8", newline="\n") as out:
                out.write(text)
    clangd = bot.dir / ".clangd"
    old = read(clangd) if clangd.exists() else "CompileFlags:\n  CompilationDatabase: .\n"
    base = old
    for start, end in ((CLANGD_START, CLANGD_END),) + OLD_CLANGD_MARKERS:
        base = re.sub(rf"\n*{re.escape(start)}.*?{re.escape(end)}[^\n]*\n?", "\n", base, flags=re.S)
    block = [f"{CLANGD_START}: lets clangd see what each file uses from the bot's other files.",
             "# Rewritten by tools/htb/hgen.py; edits between these markers are lost."]
    for f in bot.files:
        context = (Path("..") / CONTEXT_DIR.name / Path(f.rel).with_suffix(".h")).as_posix()
        block += ["---", "If:", "  PathMatch: '" + re.escape(f.rel).replace("'", "''") + "'",
                  # -mbulk-memory-opt is codegen-only and older clangds (Apple's) reject it.
                  "CompileFlags:", f"  Add: [-xc++, -include, {context}]", "  Remove: [-mbulk-memory-opt]",
                  # The bot compiles as one unit, so "include not used directly / missing" would only be noise.
                  "Diagnostics:", "  UnusedIncludes: None", "  MissingIncludes: None", f"  Suppress: [{', '.join(SUPPRESS)}]"]
    new = base.rstrip("\n") + "\n\n" + "\n".join(block + [CLANGD_END]) + "\n"
    if new != old:
        with open(clangd, "w", encoding="utf-8", newline="\n") as out:
            out.write(new)


def signature(path):
    try:
        return tuple((str(p), p.stat().st_mtime_ns) for p in bot_files(path, (SOURCE,) + HEADER_TYPES))
    except OSError:     # a file vanished mid-scan; try again next time
        return None


def watch(names, done):
    print("hgen: watching for changes (Ctrl-C to stop)")
    seen = {path: signature(path) for path in done}
    try:
        while True:
            for path in find_bots(names):
                sig = signature(path)
                if sig is not None and seen.get(path) != sig:
                    try:
                        run(path)
                    except Exception as error:  # keep watching through half-written code
                        print(f"{path.name}: hgen failed: {error!r}")
                    seen[path] = sig
            time.sleep(0.3)
    except KeyboardInterrupt:
        pass


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):   # a Windows console's code page can't show every file name
        stream.reconfigure(errors="replace")
    parser = argparse.ArgumentParser(
        prog="tools/htb/hgen.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("bots", nargs="*", help="bot names under bots/, or paths to bots "
                        "(default: every bot with .htb files in its own folder)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--watch", action="store_true", help="keep regenerating whenever a file changes")
    mode.add_argument("--check", action="store_true", help="change nothing; exit 1 if src/ is out of date")
    args = parser.parse_args(argv)
    bots = find_bots(args.bots)
    if not bots and not args.watch:
        print(f"hgen: no bot has {SOURCE} files in its own folder yet")
        return 0
    if args.check:
        return 1 if any([run(b, check=True) != "ok" for b in bots]) else 0
    refused = [run(b) == "refused" for b in bots]
    if args.watch:
        watch(args.bots, bots)
    return 1 if any(refused) else 0


if __name__ == "__main__":
    sys.exit(main())
