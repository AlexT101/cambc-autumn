"""Summarise drafts_emblems.mjs output: Fish's picks and item builds by pick count.

    py tools/fish/drafts_emblems_report.py GAMES.json.gz OUT.json OUT.md
"""
import collections
import gzip
import json
import statistics
import sys

STATS = ('Strength', 'Focus', 'Health')


def item_parts(name):
    fam, rest = name.split(' ', 1)
    kind, stat = rest.split(' of ')
    return fam, kind, stat


def short(name):
    fam, kind, stat = item_parts(name)
    return f'{fam}-{stat[0]}'


def champ_build(c):
    """Emblems in order of first formation, first-shard round per emblem, sells, consumables."""
    first_owned, first_shard, sold = {}, {}, collections.Counter()
    cons_bought, cons_first = collections.Counter(), {}
    anomalies = []
    for e in c['log']:
        for name, d in e['items'].items():
            fam, kind, stat = item_parts(name)
            key = f'{fam} Emblem of {stat}'
            if kind == 'Emblem' and d > 0:
                first_owned.setdefault(key, e['r'])
                first_shard.setdefault(key, e['r'])
                if e['kind'] != 'Shop':
                    anomalies.append((e['r'], e['kind'], name, d))
            elif kind == 'Shard' and d > 0 and e['kind'] == 'Shop':
                first_shard.setdefault(key, e['r'])
            elif d < 0 and not (kind == 'Shard' and e['kind'] == 'Shop'):
                sold[name] -= d
        for name, d in e['cons'].items():
            if d > 0:
                cons_bought[name] += d
                cons_first.setdefault(name, e['r'])
    order = sorted(first_owned, key=lambda k: (first_owned[k], k))
    return order, first_owned, first_shard, sold, cons_bought, cons_first, anomalies


def check(c):
    """Shards bought per item from the diffed log against the engine statistics, and gold spent."""
    bought = collections.Counter()
    for e in c['log']:
        if e['kind'] != 'Shop':
            continue
        for name, d in e['items'].items():
            fam, kind, stat = item_parts(name)
            n = d * (25 if fam == 'Greed' else 5) if kind == 'Emblem' else d
            bought[f'{fam} Shard of {stat}'] += n
    stats = {k: v for k, v in c['itemsBought'].items() if ' Shard ' in k}
    emblems_stat = {k: v for k, v in c['itemsBought'].items() if ' Emblem ' in k}
    emblems_log = collections.Counter()
    for e in c['log']:
        for name, d in e['items'].items():
            if ' Emblem ' in name and d > 0:
                emblems_log[name] += d
    cons_price = {'Teleport crystal': 10, 'Altar lock': 10}
    gold = 30 * sum(stats.values()) + sum(cons_price.get(k, 0) * v for k, v in c['consumablesBought'].items())
    ok_cons = set(c['consumablesBought']) <= set(cons_price)
    return ({k: v for k, v in bought.items() if v} == stats and dict(emblems_log) == emblems_stat,
            (gold == c['spentGold']) if ok_cons else None)


def pct(a, b):
    return f'{100 * a / b:.0f}%' if b else '-'


def main(src, out_json, out_md):
    data = json.load(gzip.open(src))
    games = data['games']
    assert not data['errors'], data['errors']
    by_n = collections.defaultdict(list)
    for g in games:
        by_n[g['champsPerTeam']].append(g)
    checks = [check(c) for g in games for c in g['champions']]
    summary = {'games': len(games), 'engines': dict(collections.Counter(g['engine'] for g in games)),
               'dates': [min(g['date'] for g in games), max(g['date'] for g in games)],
               'checks': {'championGames': len(checks), 'itemsMatchStatistics': sum(a for a, _ in checks),
                          'goldMatchesSpent': sum(b is True for _, b in checks), 'goldUnchecked': sum(b is None for _, b in checks)},
               'byPicks': {}}
    # Family indexing: passive counters move only for owners of that family's emblem.
    fam = collections.defaultdict(collections.Counter)
    for g in games:
        for c in g['champions']:
            owned = {item_parts(e)[0] for e, v in c['itemsBought'].items() if ' Emblem ' in e and v}
            for f, key in (('Prospector', 'prospectorGold'), ('Treasure', 'treasureGold'), ('Collectors', 'collectorsDamageBonus')):
                fam[f][f'{"owner" if f in owned else "non-owner"} {"nonzero" if c.get(key) else "zero"}'] += 1
    summary['checks']['familyPassives'] = {f: dict(v) for f, v in fam.items()}
    md = []
    w = md.append
    w('# Intercontinental Fish: drafts and emblems (2026-11-05)\n')
    w(f'{len(games)} unique Fish ladder games (sha256-deduplicated union of `manifest.json`, `confirmation-manifest.json`, '
      f'`third-manifest.json`, `fourth-manifest.json`), engines {summary["engines"]}, '
      f'{summary["dates"][0][:16]} to {summary["dates"][1][:16]} UTC. The held-out cohort (`fish-fifth-raw`, groups '
      '01a1ad0b/01a1ad15) was not read. Generated by `tools/fish/drafts_emblems.mjs` (observer snapshot every step, '
      'items diffed) and `tools/fish/drafts_emblems_report.py`; per-game rows in `drafts-emblems-games.json.gz`, '
      'tables in `drafts-emblems.json`.\n')
    w('Item ids follow the SDK `item_type` order (family x Strength/Focus/Health x shard/emblem). Stat names were checked '
      'against stat deltas at purchases (Health shards raise max health, Focus shards Focus, Strength shards Strength); '
      'five identical shards turn into one emblem in the purchase step. Shards and emblems derived from the diffed log '
      f'match the engine statistics\' `itemsBought` in {summary["checks"]["itemsMatchStatistics"]}/{len(checks)} '
      f'champion-games, and 30 gold a shard plus 10 a consumable equals `spentGold` in '
      f'{summary["checks"]["goldMatchesSpent"]}/{len(checks) - summary["checks"]["goldUnchecked"]} '
      f'(unchecked: {summary["checks"]["goldUnchecked"]}, other consumables). Emblem names below are `Family-S/F/H` '
      '(stat of the shards). Nothing was ever sold (no Tavi), so formed emblems are kept to the end.\n')
    for n in sorted(by_n):
        gs = by_n[n]
        res = {'games': len(gs)}
        wins = sum(g['winner'] == g['side'] for g in gs)
        sides = collections.Counter(g['side'] for g in gs)
        w(f'\n## {n} picks per team ({len(gs)} games, Fish won {wins}; Fish as team A {sides[0]}, B {sides[1]}; '
          f'{len({g["map"] for g in gs})} maps)\n')
        # Picks
        freq = collections.Counter(p for g in gs for p in g['fishPicks'])
        by_round = [collections.Counter(g['fishPicks'][k] for g in gs) for k in range(n)]
        res['pickFrequency'] = dict(freq.most_common())
        res['pickByRound'] = [dict(c.most_common()) for c in by_round]
        w('### Picks\n')
        w('| Champion | Games picked | ' + ' | '.join(f'Round {k}' for k in range(n)) + ' |')
        w('| --- | --- | ' + ' | '.join('---' for _ in range(n)) + ' |')
        for name, c in freq.most_common():
            w(f'| {name} | {c}/{len(gs)} ({pct(c, len(gs))}) | ' + ' | '.join(str(by_round[k][name] or '') for k in range(n)) + ' |')
        comps = collections.Counter(tuple(sorted(g['fishPicks'])) for g in gs)
        seqs = collections.Counter(tuple(g['fishPicks']) for g in gs)
        res['compositions'] = [[list(k), v] for k, v in comps.most_common()]
        res['orderedPicks'] = [[list(k), v] for k, v in seqs.most_common()]
        w(f'\n{len(comps)} distinct compositions, {len(seqs)} distinct pick orders. Most common (pick order as drafted):\n')
        w('| Games | Pick order (round 0 first) | Fish won | as A / B |')
        w('| --- | --- | --- | --- |')
        for k, v in seqs.most_common(12):
            sub = [g for g in gs if tuple(g['fishPicks']) == k]
            w(f'| {v} | {", ".join(k)} | {sum(g["winner"] == g["side"] for g in sub)} | '
              f'{sum(g["side"] == 0 for g in sub)} / {sum(g["side"] == 1 for g in sub)} |')
        # Dependence on map / side / opponent picks
        per_map = collections.defaultdict(list)
        for g in gs:
            per_map[g['map']].append(g)
        multi = {m: v for m, v in per_map.items() if len(v) > 1}
        same_map = sum(len({tuple(g['fishPicks']) for g in v}) == 1 for v in multi.values())
        modal_hits = sum(collections.Counter(tuple(g['fishPicks']) for g in v).most_common(1)[0][1] for v in per_map.values())
        ms = collections.defaultdict(list)
        for g in gs:
            ms[(g['map'], g['side'])].append(g)
        ms_multi = {k: v for k, v in ms.items() if len(v) > 1}
        ms_same = sum(len({tuple(g['fishPicks']) for g in v}) == 1 for v in ms_multi.values())
        both = [m for m in per_map if {g['side'] for g in per_map[m]} == {0, 1}]
        side_diff = sum(len({tuple(g['fishPicks']) for g in per_map[m]}) > 1 and
                        not ({tuple(g['fishPicks']) for g in per_map[m] if g['side'] == 0} &
                             {tuple(g['fishPicks']) for g in per_map[m] if g['side'] == 1}) for m in both)
        # Round-0 pick only depends on the map (no enemy pick is visible yet); later rounds could react.
        r0 = sum(len({g['fishPicks'][0] for g in v}) == 1 for v in multi.values())
        res['mapDependence'] = {'mapsWithRepeats': len(multi), 'mapsWithOneOrder': same_map, 'gamesOnModalOrder': modal_hits,
                                'mapSidePairsWithRepeats': len(ms_multi), 'mapSidePairsWithOneOrder': ms_same,
                                'mapsSeenBothSides': len(both), 'mapsWhereSidesShareNoOrder': side_diff,
                                'mapsWithOneRound0Pick': r0}
        w(f'\nMap and side: of {len(multi)} maps with 2+ games, {same_map} always got the same pick order '
          f'({r0} the same round-0 pick); {modal_hits}/{len(gs)} games used their map\'s most common order. '
          f'Same map and side: {ms_same}/{len(ms_multi)} pairs with 2+ games had one order. Of {len(both)} maps seen '
          f'from both sides, {side_diff} never shared an order between sides.\n')
        varied = sorted(((m, collections.Counter(', '.join(g['fishPicks']) for g in v)) for m, v in multi.items()
                         if len({tuple(g['fishPicks']) for g in v}) > 1), key=lambda x: -sum(x[1].values()))
        if varied:
            w('Maps where the order varied (order: games):\n')
            for m, c in varied[:10]:
                w(f'- {m}: ' + '; '.join(f'{k}: {v}' for k, v in c.most_common()))
            w('')
        # Emblems
        rows = collections.defaultdict(list)
        anomalies = []
        for g in gs:
            for c in g['champions']:
                b = champ_build(c)
                anomalies += [(g['file'], c['name'], *a) for a in b[6]]
                rows[c['name']].append((g, c, b))
        res['champions'] = {}
        w('### Emblems and items by champion\n')
        w('Per champion-game. "Distinct emblems" = distinct emblems (family and stat) ever formed; duplicates are repeat Bruiser emblems almost always; "first" = median round the first emblem formed; '
          'shards = mean shards bought (emblem shards included). Consumables are % of games buying at least one.\n')
        w('| Champion | Games | Any emblem | Distinct emblems (mean) | All emblems incl. duplicates (mean) | First emblem (median round) | Shards (mean) | Gold spent (mean) | Altar lock | Teleport crystal | Other consumables |')
        w('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
        order_names = sorted(rows, key=lambda k: -len(rows[k]))
        for name in order_names:
            r = rows[name]
            k = len(r)
            emb = [len(b[0]) for _, _, b in r]
            firsts = [min(b[1].values()) for _, _, b in r if b[1]]
            shards = [sum(v for it, v in c['itemsBought'].items() if ' Shard ' in it) for _, c, _ in r]
            spent = [c['spentGold'] for _, c, _ in r]
            lock = sum(c['consumablesBought'].get('Altar lock', 0) > 0 for _, c, _ in r)
            tp = sum(c['consumablesBought'].get('Teleport crystal', 0) > 0 for _, c, _ in r)
            other = collections.Counter(n2 for _, c, _ in r for n2, v in c['consumablesBought'].items()
                                        if v and n2 not in ('Altar lock', 'Teleport crystal'))
            alle = [sum(v for it, v in c['itemsBought'].items() if ' Emblem ' in it) for _, c, _ in r]
            w(f'| {name} | {k} | {pct(sum(e > 0 for e in emb), k)} | {statistics.mean(emb):.2f} | {statistics.mean(alle):.2f} | '
              f'{statistics.median(firsts) if firsts else "-"} | {statistics.mean(shards):.1f} | {statistics.mean(spent):.0f} | '
              f'{pct(lock, k)} ({statistics.mean(c["consumablesBought"].get("Altar lock", 0) for _, c, _ in r):.2f}/game) | '
              f'{pct(tp, k)} | {", ".join(f"{a} {b}" for a, b in other.items()) or "-"} |')
            emblem_counts = collections.Counter(e for _, _, b in r for e in b[0])
            emblem_round = {e: statistics.median([b[1][e] for _, _, b in r if e in b[1]]) for e in emblem_counts}
            emblem_pos = {e: collections.Counter(b[0].index(e) + 1 for _, _, b in r if e in b[1]) for e in emblem_counts}
            fam_shards = collections.Counter()
            for _, c, _ in r:
                for it, v in c['itemsBought'].items():
                    fam, kind, stat = item_parts(it)
                    if kind == 'Shard':
                        fam_shards[f'{fam}-{stat[0]}'] += v
            sets = collections.Counter(tuple(sorted(short(e) for e in b[0])) for _, _, b in r)
            orders = collections.Counter(tuple(short(e) for e in b[0]) for _, _, b in r)
            leftover = collections.Counter()
            for _, c, _ in r:
                for it, v in c['finalItems'].items():
                    if ' Shard ' in it:
                        leftover[short(it)] += v
            res['champions'][name] = {
                'games': k, 'withEmblem': sum(e > 0 for e in emb), 'meanEmblems': statistics.mean(emb),
                'medianFirstEmblemRound': statistics.median(firsts) if firsts else None,
                'emblems': {short(e): {'games': v, 'medianRound': emblem_round[e], 'position': dict(sorted(emblem_pos[e].items()))}
                            for e, v in emblem_counts.most_common()},
                'shardsBought': dict(fam_shards.most_common()), 'leftoverShards': dict(leftover.most_common()),
                'emblemSets': [[list(s), v] for s, v in sets.most_common()],
                'buildOrders': [[list(s), v] for s, v in orders.most_common()],
                'consumablesBought': {cn: sum(c['consumablesBought'].get(cn, 0) for _, c, _ in r)
                                      for cn in ('Teleport crystal', 'Altar lock', 'Control ward', 'TP scroll')},
                'meanSpentGold': statistics.mean(spent),
            }
        w('')
        for name in order_names:
            cr = res['champions'][name]
            if not cr['withEmblem'] and not cr['shardsBought']:
                continue
            w(f'**{name}** ({cr["games"]} games, {cr["withEmblem"]} with an emblem). Emblems formed (games, median round, '
              'position among distinct emblems): ' + '; '.join(f'{e} {v["games"]} (r{v["medianRound"]:g}, '
                                                 + ','.join(f'#{p}x{q}' for p, q in v['position'].items()) + ')'
                                                 for e, v in cr['emblems'].items()) + '.')
            w(f'Shards bought (total): ' + ', '.join(f'{f} {v}' for f, v in cr['shardsBought'].items()) +
              ('; unfinished at the end: ' + ', '.join(f'{f} {v}' for f, v in cr['leftoverShards'].items())
               if cr['leftoverShards'] else '') + '.')
            w('Build orders (first formation order: games): ' +
              '; '.join(f'{" > ".join(s) or "none"}: {v}' for s, v in cr['buildOrders'][:6]) +
              '. Emblem sets: ' + '; '.join(f'{", ".join(s) or "none"}: {v}' for s, v in cr['emblemSets'][:4]) + '.\n')
        if anomalies:
            w(f'Emblems formed outside a Shop step: {anomalies[:5]}\n')
        res['anomalies'] = anomalies
        summary['byPicks'][str(n)] = res
    w('\n## Caveats\n')
    w('- Submission versions are unknown. Splitting at 2026-11-05 12:00 UTC (the overnight `confirmation-manifest` games '
      'against the rest) shows the same pick orders per map and the same leading emblems for every champion, so no '
      'mid-day change is visible, but a change that only affects late-game builds or rare maps would not stand out.')
    w('- Every map with 2+ games got one pick order, from both sides and against every opponent, so the draft looks like '
      'a fixed function of the map (the round-0 pick cannot see enemy picks; later rounds showed no reaction). The '
      'one-off orders (Ren or Varg in 5v5) are on maps seen once.')
    w('- Round-0 Marcella versus Vesper Vale: a hand check on the 78 maps with cached map data (`replays/fish-model`) '
      'found Marcella on 36 of 41 maps with more gem than gold clusters and Vesper Vale on 25 of 37 others: a tendency, '
      'not the rule. Prism (always round 1, after Marcella) is picked only on the adgato_gemcombat maps.')
    w('- Medians of "first formed" rounds are over the games where the emblem formed, so late emblems are biased to '
      'long games. Shard counts include the shards of formed emblems.')
    json.dump(summary, open(out_json, 'w'), indent=1)
    open(out_md, 'w').write('\n'.join(md) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
