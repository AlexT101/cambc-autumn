"""Draft lab vehicles: copies of a frozen bot whose draft comes from a per-map table (trainer.h).

freeze(sha) exports a commit's bots/astraeus to bots/variants/astraeus-<sha7> (AGENTS.md); make(source, name,
entries) copies a source bot's src/ into bots/variants/<name>/, hooks draft_order() and writes the table. Files
are rewritten only when changed, so a vehicle's build cache survives between batches."""
import hashlib, json, re, shutil, subprocess, time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VARIANTS = ROOT / "bots" / "variants"
HERE = Path(__file__).resolve().parent
CAMBC = shutil.which("cambc") or "cambc"
# The SDK's champion_draft order, which the ladder's draft ids also use.
CHAMPS = ["ryth", "vesper_vale", "vendetta", "cassi_and_issac", "stellar", "prism", "marcella", "willow", "ren",
          "varg", "tavi", "heart_of_ruin"]

# (old, new) edits to the copy's draft.cc; each old must occur exactly once.
PATCHES = [
    ('#include "world.h"\n', '#include "world.h"\n#include "trainer.h"\n'),
    ("std::vector<cambc::champion_draft> draft_order() {\n",
     "std::vector<cambc::champion_draft> draft_order() {\n"
     "    if (const auto* t = trainer::lookup()) {\n"
     "        std::vector<cambc::champion_draft> out;\n"
     "        for (std::size_t i = 0; i < cambc::draft::team_size(); ++i) out.push_back(static_cast<cambc::champion_draft>(t[i]));\n"
     "        return out;\n"
     "    }\n"),
    ("if (!params::test_draft && pick == cambc::champion_draft::vesper_vale) continue;",
     "if (!params::test_draft && !trainer::lookup() && pick == cambc::champion_draft::vesper_vale) continue;"),
]


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def freeze(sha, bot="astraeus"):
    """bots/variants/<bot>-<sha7>, exported from the commit (never the working tree)."""
    sha7 = git("rev-parse", "--short=7", sha)
    target = VARIANTS / f"{bot}-{sha7}"
    if not (target / "src").is_dir():
        target.mkdir(parents=True, exist_ok=True)
        archive = subprocess.run(["git", "archive", sha, f"bots/{bot}"], cwd=ROOT, capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "--strip-components=2", "-C", str(target)], input=archive, check=True)
    return target


def write_if_changed(path, data):
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def table_header(entries):
    """entries: [(key hex, team 0/1, [champion names])], any order."""
    rows = sorted((int(k, 16), t, tuple(CHAMPS.index(c) for c in comp)) for k, t, comp in entries)
    for a, b in zip(rows, rows[1:]):
        assert a[:2] != b[:2], f"duplicate entry {a[:2]}"
    lines = [f"    {{0x{k:016x}ull, {t}, {len(c)}, {{{', '.join(map(str, c + (0,) * (5 - len(c))))}}}}},"
             for k, t, c in rows]
    # Never empty (a zero-length array is ill-formed): this sentinel's pick count matches no map.
    lines.append("    {0xffffffffffffffffull, 255, 0, {0, 0, 0, 0, 0}},")
    return ("#pragma once\n// Generated by tools/draftlab/vehicle.py: (map key, team, picks, draft ids), sorted.\n"
            "namespace aph::trainer {\ninline constexpr Entry entries[] = {\n" + "\n".join(lines) + "\n};\n}\n")


def make(source, name, entries):
    source = Path(source)
    target = VARIANTS / name
    blobs = {}
    for path in (source / "src").rglob("*"):
        if path.is_file():
            blobs[path.relative_to(source).as_posix()] = path.read_bytes()
    params = blobs["src/params.h"].decode()
    assert re.search(r"constexpr bool test_draft = false;", params), "the source's test_draft must be off"
    raw = blobs["src/draft.cc"].decode()
    text = raw.replace("\r\n", "\n")
    for old, new in PATCHES:
        assert text.count(old) == 1, f"draft.cc patch point not found once: {old[:60]!r}"
        text = text.replace(old, new)
    blobs["src/draft.cc"] = (text.replace("\n", "\r\n") if "\r\n" in raw else text).encode()
    blobs["src/trainer.h"] = (HERE / "trainer.h").read_bytes()
    blobs["src/trainer_table.h"] = table_header(entries).encode()
    changed = [rel for rel, data in sorted(blobs.items()) if write_if_changed(target / rel, data)]
    for path in sorted((target / "src").rglob("*"), reverse=True):
        if path.is_file() and path.relative_to(target).as_posix() not in blobs:
            path.unlink()
            changed.append(path.name)
    stamp = {"source": source.relative_to(ROOT).as_posix() if source.is_relative_to(ROOT) else str(source),
             "src_sha1": src_hash(source), "entries": len(entries)}
    write_if_changed(target / "vehicle.json", (json.dumps(stamp, indent=1) + "\n").encode())
    return target, bool(changed)


def src_hash(bot):
    h = hashlib.sha1()
    for f in sorted((Path(bot) / "src").rglob("*")):
        if f.is_file():
            h.update(f.relative_to(bot).as_posix().encode() + b"\0" + f.read_bytes())
    return h.hexdigest()[:10]


def built(path):
    return (Path(path) / ".cambc" / "build" / "bot-injected.wasm").is_file()


def build(path):
    r = subprocess.run([CAMBC, "build", str(path)], cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
                       errors="replace")
    return path, r.returncode, r.stdout[-2000:] + r.stderr[-2000:]


def build_all(paths, par=6):
    paths = list(dict.fromkeys(paths))
    t = time.time()
    with ThreadPoolExecutor(par) as ex:
        for path, code, out in ex.map(build, paths):
            if code:
                shutil.rmtree(Path(path) / ".cambc", ignore_errors=True)
                raise RuntimeError(f"build failed {path}:\n{out}")
    return time.time() - t
