"""Rewrite a bot's draft.cc test_compositions tables from a draft-lab prior.json: per pick count the `--top` most
frequent compositions, in their pick order, each with its weight (the prior's n, scaled to integers), so choose()
picks by frequency, deterministic per map and side.

    py tools/draftlab/test_comps.py --prior replays/draftlab/LAB/prior.json --bot bots/ocean [--top 16]
"""
import argparse
import json
import re
from pathlib import Path

NAMES = {3: "three", 4: "four", 5: "five"}


def block(prior, top):
    out = ["namespace test_compositions {", "using C = cambc::champion_draft;",
           f"// Generated by tools/draftlab/test_comps.py from {prior['_path']}: the {top} most frequent compositions",
           "// per pick count, in pick order, weighted by frequency.",
           "template <std::size_t N> struct Weighted {", "    std::uint32_t weight;", "    C team[N];", "};"]
    for p in (3, 4, 5):
        comps = sorted(prior.get(str(p), []), key=lambda e: -e["n"])[:top]
        total = sum(e["n"] for e in comps) or 1
        out.append(f"constexpr Weighted<{p}> {NAMES[p]}[] = {{")
        for e in comps:
            w = max(1, round(1000 * e["n"] / total))
            out.append(f"    {{{w}, {{{', '.join('C::' + c for c in e['comp'])}}}}},")
        out.append("};")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prior", required=True)
    ap.add_argument("--bot", required=True)
    ap.add_argument("--top", type=int, default=16)
    args = ap.parse_args()
    prior = json.loads(Path(args.prior).read_text())
    prior["_path"] = args.prior
    f = Path(args.bot) / "src" / "draft" / "draft.cc"
    s = f.read_text()
    start = s.index("namespace test_compositions {")
    mix = s.index("std::uint64_t mix(std::uint64_t h, std::uint64_t w) {", start)
    s = s[:start] + "\n".join(block(prior, args.top)) + "\n\n" + s[mix:]
    old = re.search(r"std::span<const C> choose\(\) \{.*?\n\}\n", s, re.S)
    new = """std::span<const C> choose() {
    const auto picks = cambc::draft::team_size();
    const auto pick = [&](const auto& table) -> std::span<const C> {
        std::uint64_t total = 0;
        for (const auto& e : table) total += e.weight;
        auto r = map_hash() % total;
        for (const auto& e : table) {
            if (r < e.weight) return e.team;
            r -= e.weight;
        }
        return table[0].team;
    };
    if (picks == 3) return pick(three);
    if (picks == 4) return pick(four);
    if (picks == 5) return pick(five);
    return params::draft_preference;
}
"""
    s = s[:old.start()] + new + s[old.end():]
    f.write_text(s)
    print(f"rewrote {f}: test_compositions from {args.prior}")


if __name__ == "__main__":
    main()
