//! Builds the wasm engine backend (FASTRUNNER_ENGINE=wasm, src/wengine.rs): cambc's engine from the viewer's WASM
//! build (tools/replay/engine/v3_0_0.wasm), translated by wabt's wasm2c and compiled by clang into a static library,
//! with wengine/glue.c. Needs wasm2c (wabt 1.0.36; its wasm-rt.h), clang and simde headers (setup_vendor.sh). If any
//! is missing the runner is built without the backend (cfg `wasm_engine` unset) and says so.
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo::rustc-check-cfg=cfg(wasm_engine)");
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let wasm = std::env::var_os("FASTRUNNER_ENGINE_WASM")
        .map(PathBuf::from)
        .unwrap_or_else(|| dir.join("../../replay/engine/v3_0_0.wasm"));
    for v in ["FASTRUNNER_ENGINE_WASM", "FASTRUNNER_WASM2C", "FASTRUNNER_CC", "FASTRUNNER_SIMDE"] {
        println!("cargo:rerun-if-env-changed={v}");
    }
    println!("cargo:rerun-if-changed={}", wasm.display());
    println!("cargo:rerun-if-changed=wengine/glue.c");
    println!("cargo:rerun-if-changed=build.rs");
    if let Err(e) = build(&dir, &wasm) {
        println!("cargo:warning=wasm engine backend not built: {e}");
    }
}

fn build(dir: &Path, wasm: &Path) -> Result<(), String> {
    if std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() != Ok("x86_64") {
        return Err("x86-64 only".into());
    }
    if !wasm.exists() {
        return Err(format!("{} missing", wasm.display()));
    }
    let wasm2c = std::env::var("FASTRUNNER_WASM2C").unwrap_or_else(|_| "wasm2c".into());
    let cc = std::env::var("FASTRUNNER_CC").unwrap_or_else(|_| "clang".into());
    let simde = [std::env::var_os("FASTRUNNER_SIMDE").map(PathBuf::from), Some(dir.join("vendor/simde/include")), Some("/usr/include".into())]
        .into_iter()
        .flatten()
        .find(|p| p.join("simde/wasm/simd128.h").exists())
        .ok_or("no simde headers (run setup_vendor.sh)")?;
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("wengine");
    let _ = std::fs::remove_dir_all(&out);
    std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
    // Eight parts compile in parallel (one is ~17 s at -O2).
    const PARTS: usize = 8;
    let st = Command::new(&wasm2c)
        .arg(wasm)
        .arg("-o")
        .arg(out.join("engine.c"))
        .args(["-n", "engine", &format!("--num-outputs={PARTS}")])
        .status()
        .map_err(|e| format!("{wasm2c}: {e}"))?;
    if !st.success() {
        return Err(format!("{wasm2c} failed"));
    }
    exports(&out)?;
    let mut srcs: Vec<PathBuf> = (0..PARTS).map(|i| out.join(format!("engine_{i}.c"))).collect();
    srcs.push(dir.join("wengine/glue.c"));
    // As the bots' native code: wasm float semantics need no contraction; guard pages replace bounds checks.
    let flags = ["-O2", "-fPIC", "-march=x86-64-v3", "-ffp-contract=off", "-fno-math-errno", "-w"];
    let jobs: Vec<_> = srcs
        .iter()
        .map(|s| {
            let o = out.join(s.file_stem().unwrap()).with_extension("o");
            let mut c = Command::new(&cc);
            c.args(flags).arg("-I").arg(&out).arg("-I").arg(&simde).arg("-c").arg(s).arg("-o").arg(&o);
            (c.spawn(), o)
        })
        .collect();
    let mut objs = Vec::new();
    for (child, o) in jobs {
        let ok = child.map_err(|e| format!("{cc}: {e}"))?.wait().map_err(|e| e.to_string())?.success();
        if !ok {
            return Err(format!("{cc} failed on {}", o.display()));
        }
        objs.push(o);
    }
    let lib = out.join("libfrwengine.a");
    let st = Command::new("ar").arg("crs").arg(&lib).args(&objs).status().map_err(|e| format!("ar: {e}"))?;
    if !st.success() {
        return Err("ar failed".into());
    }
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rustc-link-lib=static=frwengine");
    println!("cargo:rustc-cfg=wasm_engine");
    Ok(())
}

/// exports.rs: an extern declaration of every function the engine exports (`w2c_engine_<export>(instance, ...)`),
/// from wasm2c's engine.h, for wengine.rs and later callers (the sandbox, the visualiser API).
fn exports(out: &Path) -> Result<(), String> {
    let h = std::fs::read_to_string(out.join("engine.h")).map_err(|e| e.to_string())?;
    let mut rs = String::from("// Generated by build.rs from wasm2c's engine.h.\nextern \"C\" {\n");
    let mut lines = h.lines();
    let ty = |t: &str| match t.trim() {
        "u32" => Some("u32"),
        "u64" => Some("u64"),
        "f32" => Some("f32"),
        "f64" => Some("f64"),
        _ => None,
    };
    while let Some(l) = lines.next() {
        if !l.starts_with("/* export: ") {
            continue;
        }
        let Some(p) = lines.next() else { break };
        let Some((head, args)) = p.trim_end_matches(");").split_once('(') else { continue };
        let Some((ret, name)) = head.split_once(' ') else { continue };
        if !name.starts_with("w2c_engine_") || !args.starts_with("w2c_engine*") || name == "w2c_engine_memory" {
            continue;
        }
        let mut ps = vec!["i: *mut W2c".to_string()];
        let mut ok = true;
        for (k, a) in args.split(',').skip(1).enumerate() {
            match ty(a) {
                Some(t) => ps.push(format!("a{k}: {t}")),
                None => ok = false,
            }
        }
        let r = match ret {
            "void" => String::new(),
            t => match ty(t) {
                Some(t) => format!(" -> {t}"),
                None => {
                    ok = false;
                    String::new()
                }
            },
        };
        if ok {
            rs.push_str(&format!("    pub fn {name}({}){r};\n", ps.join(", ")));
        }
    }
    rs.push_str("}\n");
    std::fs::write(out.join("exports.rs"), rs).map_err(|e| e.to_string())
}
