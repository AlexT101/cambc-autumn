// Writes a puppet bot that replays one team's recorded inputs (inputs.mjs output).
//   node tools/replay/harness/gen_puppet.mjs <inputs.json[.gz]> <team 0|1> <bot dir>
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { K } from './inputs.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const A = { MOVE: 1, ATTACK: 2, CAST: 3, PRIORITY: 4, RECALL: 5, SUBMIT: 6, BUY: 7, SELL: 8, BUY_CONS: 9, WARD: 10, CANCEL: 11, LOCK: 12, TELEPORT: 13, BLOCKED: 14, RESIGN: 15, USE_CONS: 16 };
// blocked() in main.cpp tries these in order, one nibble each.
const B = { move: 1, dash: 2, ward: 3, teleport: 4 };
const order = (...w) => w.reduce((acc, x, i) => acc | (B[x] << (4 * i)), 0);

export function loadInputs(file) {
  const raw = fs.readFileSync(file);
  return JSON.parse(file.endsWith('.gz') ? zlib.gunzipSync(raw) : raw);
}

// Rejected tries cost nothing and every blocked try records the same step, so all feasible actions
// are tried; ward first where an allied ward could be the hidden blocker (most opponent blocks).
function blockedOrder(r) {
  const flags = r[14], dist = Math.max(Math.abs(r[7] - r[9]), Math.abs(r[8] - r[10]));
  const ward = flags & 2, walked = flags & 4;
  const w = [];
  if (ward && dist <= 2) w.push('ward');
  if (dist === 1 && !walked) w.push('move');
  if (dist <= 2) w.push('dash');
  if (dist <= 3) w.push('teleport');
  return order(...w);
}

// Leaves an unchanged file alone so that its build stays up to date.
function writeIfChanged(file, data) {
  if (fs.existsSync(file) && fs.readFileSync(file).equals(data)) return false;
  fs.writeFileSync(file, data);
  return true;
}

export function puppetScript(d, team) {
  const ids = new Set(d.roster.filter(c => c.team === team).map(c => c.id));
  const turns = new Map(), problems = [], rollovers = new Set();
  for (const r of d.inputs) {
    const [s, round, , kind, phase, actorKind, actor] = r;
    if (phase !== 10 || actorKind !== 1 || !ids.has(actor)) continue;
    let a;
    const [tx, ty] = [r[9], r[10]];
    switch (kind) {
      case K.Move: a = [A.MOVE, tx, ty, 0, 0]; break;
      case K.Attack: a = [A.ATTACK, tx, ty, r[14], 0]; break;
      case K['Cast ability']: a = [A.CAST, tx, ty, r[11], r[14]]; break;
      case K['Set priority']: a = [A.PRIORITY, 0, 0, r[13], 0]; break;
      case K.Recall: a = [A.RECALL, 0, 0, 0, 0]; break;
      case K['Submit gems']: a = [A.SUBMIT, tx, ty, 0, 0]; break;
      case K.Shop:
        if (r[14] < 0) problems.push(`s${s}: shop with no item change`);
        a = r[14] >= 100 ? [A.BUY_CONS, 0, 0, r[14] - 100, r[15]] : [A.BUY, 0, 0, r[14], r[15]];
        break;
      case K['Sell item']: a = [A.SELL, 0, 0, r[14], r[15]]; break;
      case K.Consumable: a = [A.USE_CONS, tx, ty, r[14], 0]; problems.push(`s${s}: Consumable step (unverified mapping)`); break;
      case K['Place ward']: a = [A.WARD, tx, ty, 0, 0]; break;
      case K['Cancel channel']: a = [A.CANCEL, 0, 0, 0, 0]; break;
      case K['Place altar lock']: a = [A.LOCK, tx, ty, 0, 0]; break;
      case K['Teleport channel']: a = [A.TELEPORT, tx, ty, 0, 0]; break;
      case K['Movement blocked']: a = [A.BLOCKED, tx, ty, blockedOrder(r), 0]; break;
      case K.Resign: a = [A.RESIGN, 0, 0, 0, 0]; break;
      case K['Turn rollover']: rollovers.add(round * 64 + actor); if (!turns.has(round * 64 + actor)) turns.set(round * 64 + actor, []); continue;
      case K['End turn']: continue;
      case K['Bot error']: problems.push(`s${s}: Bot error (not reproduced)`); continue;
      default: problems.push(`s${s}: unhandled input kind ${kind}`); continue;
    }
    const key = round * 64 + actor;
    if (!turns.has(key)) turns.set(key, []);
    turns.get(key).push([...a, s]);
  }
  const keys = [...turns.keys()].sort((x, y) => x - y);
  return { keys, turns, rollovers, draft: d.draft.picks[team].slice(0, d.draft.counts[team]), problems };
}

export function writePuppet(d, team, dir) {
  const { keys, turns, rollovers, draft, problems } = puppetScript(d, team);
  fs.mkdirSync(path.join(dir, 'src'), { recursive: true });
  const changed = writeIfChanged(path.join(dir, 'src', 'main.cpp'), fs.readFileSync(path.join(HERE, 'puppet', 'main.cpp')));
  const starts = [0], acts = [];
  for (const k of keys) { for (const a of turns.get(k)) acts.push(a); starts.push(acts.length); }
  const chunk = (arr, w = 24) => { const out = []; for (let i = 0; i < arr.length; i += w) out.push(arr.slice(i, i + w).join(',')); return out.join(',\n'); };
  const src = `// Generated by tools/replay/harness/gen_puppet.mjs from ${d.key ?? 'a replay'}, team ${team}.
#pragma once
#include <cstdint>
namespace script {
inline constexpr int draft_count = ${draft.length};
inline constexpr int draft[${Math.max(1, draft.length)}] = {${draft.join(',') || 0}};
inline constexpr int turn_count = ${keys.length};
inline constexpr std::int64_t turn_keys[${Math.max(1, keys.length)}] = {
${chunk(keys) || 0}};
inline constexpr int turn_start[${starts.length}] = {
${chunk(starts)}};
// Turns the original bot ran out of fuel in: the puppet spins after its actions until it does too.
inline constexpr int rollover_count = ${rollovers.size};
inline constexpr std::int64_t rollover_keys[${Math.max(1, rollovers.size)}] = {
${chunk([...rollovers].sort((x, y) => x - y)) || 0}};
// kind, x, y, p, q, source step
inline constexpr int actions[${Math.max(6, acts.length * 6)}] = {
${chunk(acts.flat()) || '0,0,0,0,0,0'}};
}
`;
  const changedScript = writeIfChanged(path.join(dir, 'src', 'script.h'), Buffer.from(src));
  return { actions: acts.length, turns: keys.length, rollovers: rollovers.size, changed: changed || changedScript, problems };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [file, team, dir] = process.argv.slice(2);
  const r = writePuppet(loadInputs(file), +team, dir);
  console.log(JSON.stringify({ actions: r.actions, turns: r.turns, rollovers: r.rollovers, changed: r.changed, problems: r.problems.slice(0, 20), nProblems: r.problems.length }));
}
