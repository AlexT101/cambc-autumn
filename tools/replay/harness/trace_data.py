"""Compile a recorder run's @f/@r/@y lines into rec_data.cpp for the tracer (harness_trace.h).

    py tools/replay/harness/trace_data.py REC_STDOUT OUT.cpp [--game KEY] [--level N] [--rounds R0-R1]

--level and --rounds set the traced bot's verbosity (TRACE_SCHEMA.md): level 2 detail is printed only
for rounds R0..R1. They live here so that changing them rebuilds only this file.

REC_STDOUT is our team's stdout from the recorder run (a replay bundle's team-X.stdout, NULs allowed).
Writes the file only if its content changed, so an unchanged game does not rebuild.
"""
import argparse
import re
from collections import defaultdict
from pathlib import Path


# A record is a whole line; older recorder output could start one in the middle of a line of the
# bot's own (buffered printf), so it is searched for, not matched at the line start. @x lines and
# blank lines are skipped.
REC = re.compile(r"@([fry]) (-?\d+) (\d+) (\d+) (-?\d+)(?: (\d+))?$")


def parse(text):
    f, r, y = defaultdict(list), defaultdict(list), defaultdict(dict)
    for line in text.replace("\0", "").splitlines():
        at = line.find("@")
        if at < 0:
            continue
        m = REC.search(line, at)
        if not m:
            continue
        kind, me, seg, a, b = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4)), int(m.group(5))
        if kind == "f":
            f[me].append((seg, a, b))
        elif kind == "r":
            r[me].append((seg, a, b))
        else:
            y[me][seg] = (a, b, int(m.group(6)))
    return f, r, y


def render(f, r, y, game, level=1, r0=0, r1=1 << 30):
    out = ["// Generated by tools/replay/harness/trace_data.py: do not edit.", '#include "harness_trace_data.h"']
    insts = []
    for me in sorted(set(f) | set(r) | set(y)):
        tag = f"m{me + 1}"
        segs = y.get(me, {})
        n = max(segs) + 1 if segs else 0
        missing = [s for s in range(n) if s not in segs]
        if missing:
            raise SystemExit(f"champion {me}: segments missing from @y: {missing[:5]}")
        fs, rs = sorted(f.get(me, [])), sorted(r.get(me, []))
        out.append(f"static const HtF f{tag}[] = {{" + ",".join(f"{{{s},{i},{v}}}" for s, i, v in fs) + ("" if fs else "{0,0,0}") + "};")
        out.append(f"static const HtR r{tag}[] = {{" + ",".join(f"{{{s},{i},{v}}}" for s, i, v in rs) + ("" if rs else "{0,0,0}") + "};")
        out.append(f"static const HtY y{tag}[] = {{" + ",".join("{%d,%d,%du}" % segs[s] for s in range(n)) + ("" if n else "{0,0,0}") + "};")
        insts.append(f"{{{me},{len(fs)},{len(rs)},{n},f{tag},r{tag},y{tag}}}")
    out.append('extern "C" const HtInst ht_insts[] = {' + ",".join(insts) + "};")
    out.append(f'extern "C" const uint32_t ht_ninst = {len(insts)};')
    out.append(f'extern "C" const char ht_game[] = "{game}";')
    out.append(f'extern "C" int32_t ht_trace_level = {level}, ht_trace_r0 = {r0}, ht_trace_r1 = {r1};')
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rec_stdout")
    ap.add_argument("out")
    ap.add_argument("--game", default="")
    ap.add_argument("--level", type=int, default=1)
    ap.add_argument("--rounds", default="", help="R0-R1: the level 2 window")
    args = ap.parse_args()
    r0, r1 = (int(x) for x in args.rounds.split("-")) if args.rounds else (0, 1 << 30)
    f, r, y = parse(Path(args.rec_stdout).read_text(encoding="utf-8", errors="replace"))
    text = render(f, r, y, args.game, args.level, r0, r1)
    out = Path(args.out)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    print(f"{sum(map(len, f.values()))} fuel reads, {sum(map(len, r.values()))} out-of-fuel points, "
          f"{sum(map(len, y.values()))} segments, {len(y)} instances -> {out}")


if __name__ == "__main__":
    main()
