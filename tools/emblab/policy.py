"""astraeus's learned emblem table (src/economy/emblem_table.h) from a fit's policy file (fit.mjs --boot N):
per pick count, champion type and new-emblem ordinal, the fit's best arm where the 10th percentile of its gain
over the current logic's choice across bootstrap refits is above --min-p10 (win points), else the current logic.

    py tools/emblab/policy.py [replays/emblab/main/model.policy.json] [--min-p10 0] [--out bots/astraeus/src/economy/emblem_table.h]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TYPES = ["ryth", "vesper_vale", "vendetta", "cassi", "issac", "stellar", "prism", "marcella", "willow", "ren", "varg", "tavi", "heart_of_ruin"]
PICKS = [3, 4, 5]
ORDINALS = 8
CURRENT = 255
PTS = 25  # win points per logit near 50%


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("policy", nargs="?", default=str(ROOT / "replays/emblab/main/model.policy.json"))
    ap.add_argument("--min-p10", type=float, default=0.0)
    ap.add_argument("--out", default=str(ROOT / "bots/astraeus/src/economy/emblem_table.h"))
    a = ap.parse_args()
    pol = json.loads(Path(a.policy).read_text())
    assert pol["boots"] >= 10, "fit with --boot 10 or more"
    kbs = pol["buckets"]
    cells = {(c["picks"], c["type"], c["kb"]): c for c in pol["cells"]}
    table, notes, used = [], [], 0
    for p in PICKS:
        rows = []
        for t in TYPES:
            arms = []
            for k in range(ORDINALS):
                c = cells.get((p, t, min(k, kbs - 1)))
                ok = c and c["gain"] > 0 and PTS * c["p10"] > a.min_p10
                arms.append(c["arm"] if ok else CURRENT)
                if ok and k < kbs:
                    notes.append(f"{p} picks {t} {k if k < kbs - 1 else f'{k}+'}: {c['name']} {PTS * c['gain']:+.1f} "
                                 f"(p10 {PTS * c['p10']:+.1f}, {100 * c['agree']:.0f}%)")
            used += sum(x != CURRENT for x in arms)
            rows.append("        {" + ", ".join(map(str, arms)) + "}, // " + t)
        table.append("    {\n" + "\n".join(rows) + "\n    },")
    src = Path(a.policy).resolve()
    rel = src.relative_to(ROOT) if src.is_relative_to(ROOT) else src
    out = ("#pragma once\n"
           f"// Generated by tools/emblab/policy.py from {rel} (min p10 {a.min_p10:g} win points).\n"
           "// learned_arm[picks - 3][champion_type][ordinal]: family * 3 + stat of the champion's ordinal-th new emblem, or\n"
           f"// {CURRENT} for the current logic's choice. Win points over the current logic (p10, bootstrap agreement):\n"
           + "".join(f"//   {n}\n" for n in notes) +
           "#include <cstdint>\n\nnamespace aph {\n\n"
           f"inline constexpr std::uint8_t learned_arm[{len(PICKS)}][{len(TYPES)}][{ORDINALS}] = {{\n" + "\n".join(table) + "\n};\n\n}\n")
    Path(a.out).write_text(out)
    print(f"{used} of {len(PICKS) * len(TYPES) * ORDINALS} (pick count, type, ordinal) cells learned -> {a.out}")


if __name__ == "__main__":
    main()
