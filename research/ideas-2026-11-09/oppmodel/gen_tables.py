"""Fit the classifier on every side from 11-08 on and write the bot's table header.

usage: gen_tables.py OUT.h [--before ISO]
"""
import sys
import numpy as np
from evaluate import load
from model import Model, PRIOR
from tokens import TOK

def main():
    out = sys.argv[1]
    rows = load()
    if '--before' in sys.argv:
        b = sys.argv[sys.argv.index('--before') + 1]
        rows = [s for s in rows if s['created'] < b]
    kw = {}
    if '--draft_cap' in sys.argv: kw['draft_cap'] = float(sys.argv[sys.argv.index('--draft_cap') + 1])
    m = Model(**kw).fit(rows)
    f = lambda x: f'{float(x):.7e}f'
    L = ['// Generated by research/ideas-2026-11-09/oppmodel/gen_tables.py: do not edit.', '#pragma once', '#include <cstdint>', '',
         'namespace aph::opp::tables {', f'inline constexpr int tokens = {len(TOK)};',
         f'inline constexpr float tau = {f(m.tau)};',
         '// log prior: fish, mite, other',
         'inline constexpr float prior[3] = {' + ', '.join(f(x) for x in PRIOR) + '};',
         '// Sub-models (a class and a variant of its encoding): class, log weight within class, log P(token | sub-model).',
         f'inline constexpr int subs = {len(m.sub_cls)};',
         'inline constexpr int sub_class[subs] = {' + ', '.join(str(int(c)) for c in m.sub_cls) + '};',
         'inline constexpr float sub_log_w[subs] = {' + ', '.join(f(x) for x in m.sub_logw) + '};',
         '// Left out when N+1 divides 100 (rank structure alone is then common among other teams).',
         'inline constexpr bool sub_gated[subs] = {' + ', '.join('true' if g else 'false' for g in m.sub_gated) + '};',
         '// tokens in order: ' + ' '.join(TOK),
         'inline constexpr float log_p[subs][tokens] = {']
    for c in range(len(m.sub_cls)): L.append('    {' + ', '.join(f(x) for x in m.logP[c]) + '},')
    L.append('};')
    # draft[pick id][picks - 3][class][slot]; 0 where unseen
    D = np.zeros((12, 3, 3, 5))
    for (ch, n), t in m.draft.items():
        if 3 <= n <= 5: D[ch, n - 3, :, :n] = t
    L.append('// log P(pick slot | champion, pick count, class): [draft pick id][picks - 3][class][slot]')
    L.append('inline constexpr float draft[12][3][3][5] = {')
    for ch in range(12):
        L.append('    {' + ', '.join('{' + ', '.join('{' + ', '.join(f(x) for x in D[ch, n, c]) + '}' for c in range(3)) + '}' for n in range(3)) + '},')
    L.append('};')
    L.append(f'inline constexpr float draft_cap = {f(m.draft_cap if m.draft_cap is not None else 1e9)};')
    L.append('} // namespace aph::opp::tables')
    open(out, 'w').write('\n'.join(L) + '\n')
    np.set_printoptions(precision=3, suppress=True)
    print(np.exp(m.logP))

if __name__ == '__main__':
    main()
