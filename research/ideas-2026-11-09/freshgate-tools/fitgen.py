"""Fit Fish's and Mite's pick models (multinomial logit over the comps each used, on the 92 draft-lab map features,
standardised and clamped at +-4, NaN as 0) to their live drafts in our scrims, report grouped-CV accuracy, and write
the bodies' header.   py fitgen.py OUT_DIR"""
import json, sys, collections, numpy as np, warnings, os
from sklearn.linear_model import LogisticRegression
warnings.filterwarnings('ignore')
P_ = os.path.dirname(os.path.abspath(__file__)) + '/'
NAMES = json.load(open(P_ + 'names.json'))
FT = {x['name'].replace('_', '-'): x['f'] for x in map(json.loads, open('/home/ubuntu/tmp-offload/diverse/fresh/feat-ladder.jsonl'))}
G = [json.loads(l) for l in open('/home/ubuntu/cambc-autumn/research/ladder-scrims-2026-11-06/data/games.jsonl')]
C = 0.3
# Features measured only on request (map_features.h: dash_gain on, to sight_gap) cost the bodies' first draft turn
# enough to cap its later sections: left out, so the bodies call compute() with want = 0.
EXP = ('dash_gain', 'narrow', 'spawn_ring', 'max_group', 'camp_altar', 'sight_gap')
KEEP = np.array([not any(e in n for e in EXP) for n in NAMES])
def raw(f): return np.array([0.0 if f.get(n) is None or not np.isfinite(f.get(n)) else float(f[n]) for n in NAMES])
Xall = np.array([raw(f) for f in FT.values()]); MU, SD = Xall.mean(0), Xall.std(0); SD[SD < 1e-9] = 1.0
def z(f): return np.clip((raw(f) - MU) / SD, -4, 4) * KEEP
enum = lambda n: n.lower().replace(' & ', '_and_').replace(' ', '_')
out = {}
for o, tag in (('F', 'Inte'), ('M', 'Mite')):
    cnt = collections.defaultdict(collections.Counter); order = collections.defaultdict(collections.Counter)
    for g in G:
        if g['opp_name'][:4] != tag or not g.get('opp_picks') or g['status'] != 'finished': continue
        m = g['map'].replace('_', '-')
        if m not in FT: continue
        comp = '|'.join(sorted(g['opp_picks'])); cnt[m][comp] += 1; order[comp][tuple(g['opp_picks'])] += 1
    for P in (3, 4, 5):
        maps = [m for m in cnt if len(next(iter(cnt[m])).split('|')) == P]
        rows = [(m, c, w / sum(cnt[m].values())) for m in maps for c, w in cnt[m].items()]
        X = np.array([z(FT[m]) for m, _, _ in rows]); y = [c for _, c, _ in rows]; w = np.array([x for *_, x in rows])
        comps = sorted(set(y)); modal = collections.Counter({c: 0.0 for c in comps})
        for (m, c, ww) in rows: modal[c] += ww
        # grouped CV by map: accuracy against each map's observed comp mix, and champion overlap
        acc = ovl = base = 0.0
        for m in maps:
            tr = [i for i, r in enumerate(rows) if r[0] != m]
            yt = [y[i] for i in tr]
            if len(set(yt)) < 2: pred = yt[0]
            else: pred = LogisticRegression(C=C, max_iter=3000).fit(X[tr], yt, sample_weight=w[tr]).predict(z(FT[m])[None])[0]
            tot = sum(cnt[m].values())
            acc += cnt[m][pred] / tot
            ovl += sum(v / tot * len(set(pred.split('|')) & set(c.split('|'))) / P for c, v in cnt[m].items())
            mc = collections.Counter(); [mc.update({c: ww}) for (mm, c, ww) in rows if mm != m]; bp = mc.most_common(1)[0][0]
            base += cnt[m][bp] / tot
        n = len(maps)
        print(f'{o} picks {P}: {n} maps, {len(comps)} comps; held-out exact comp {acc/n:.2f} (modal-comp baseline {base/n:.2f}), champion overlap {ovl/n:.2f}')
        if len(comps) == 1: b = np.zeros(1); W = np.zeros((1, len(NAMES)))
        else:
            model = LogisticRegression(C=C, max_iter=3000).fit(X, y, sample_weight=w)
            assert list(model.classes_) == comps
            b, W = model.intercept_, model.coef_
            if len(comps) == 2: b = np.array([0.0, b[0]]); W = np.vstack([np.zeros(len(NAMES)), W[0]])
        out[(o, P)] = [(c, list(order[c].most_common(1)[0][0]), float(b[i]), W[i]) for i, c in enumerate(comps)]
od = sys.argv[1]
for o in 'FM':
    L = ['#pragma once', f"// Generated by research/ideas-2026-11-09/freshgate-tools/fitgen.py: {'Fish' if o == 'F' else 'Mite'}'s pick model.",
         '// Multinomial logit over the comps it drafted in our scrims, on the 92 draft-lab map features (draft/map_features.h',
         '// names order) standardised over the 128 ladder maps and clamped at +-4, a NaN read as 0. No map identity.',
         '#include <cstdint>', 'namespace fm {', 'using C = cambc::champion_draft;', f'inline constexpr bool sample = {"true" if o == "M" else "false"};',
         'inline constexpr double mu[92] = {' + ', '.join(f'{v:.10g}' for v in MU) + '};',
         'inline constexpr double sd[92] = {' + ', '.join(f'{v:.10g}' for v in SD) + '};',
         'struct Comp { int n; C picks[5]; double b; double w[92]; };', 'inline constexpr Comp comps[] = {']
    for P in (3, 4, 5):
        for c, ordr, b, W in out[(o, P)]:
            L.append(f"    {{{P}, {{{', '.join('C::' + enum(p) for p in ordr)}}}, {b:.10g}, {{{', '.join(f'{v:.8g}' for v in W)}}}}}, // {c}")
    L += ['};', '}', '']
    open(os.path.join(od, f'fm_draft_{o}.h'), 'w').write('\n'.join(L))
print('wrote', od)
