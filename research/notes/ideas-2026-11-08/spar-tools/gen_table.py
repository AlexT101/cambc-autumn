"""Write BOT/src/draft/spar_draft.h: the live opponent's (F, M) exact picks per (ladder map, side the spar bot plays).
   py gen_table.py F bots/variants/spar-oc29-F [hashes.json]"""
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__)); import live
opp, bot = sys.argv[1], sys.argv[2]
H = json.load(open(sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(__file__), 'hashes.json')))
enum = lambda n: n.lower().replace(' & ', '_and_').replace(' ', '_')
dr = live.drafts(); rows = []
for key, h in sorted(H.items()):
    m, side = key.split(':'); ours = 'b' if side == 'a' else 'a'
    if (m, ours, opp) not in dr: continue
    picks = dr[(m, ours, opp)][0]
    rows.append(f"    {{{h}ull, {len(picks)}, {{{', '.join('C::' + enum(p) for p in picks)}}}}}, // {m} {side}")
open(os.path.join(bot, 'src/draft/spar_draft.h'), 'w').write(
    '#pragma once\n// Generated by research/notes/ideas-2026-11-08/spar-tools/gen_table.py: live ' + opp + "'s picks per ladder map and side.\n"
    '#include <cstdint>\nnamespace spar {\nusing C = cambc::champion_draft;\n'
    'struct Entry { std::uint64_t hash; int n; C picks[5]; };\ninline constexpr Entry table[] = {\n' + '\n'.join(rows) + '\n};\n}\n')
print(bot, len(rows), 'entries')
