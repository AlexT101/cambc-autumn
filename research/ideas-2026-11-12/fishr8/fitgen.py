"""Fish r8's pick model, as mitefit/fitgen_r7.py: a multinomial logit over the comps Fish r8 drafted in our scrims
(capture rows, ~/tmp-offload/fishr8/ours.json) on the 92 draft-lab map features (standardised over the 128 ladder maps
as before, clamped at +-4, NaN as 0), fitted on all 170 ranked maps; grouped-CV accuracy by map. Fish's draft is a
deterministic function of the map, so the body takes the most likely comp (sample = false).
    py fitgen.py OUT_DIR   (writes fm_draft_F.h)"""
import json, sys, collections, numpy as np, warnings, os
from sklearn.linear_model import LogisticRegression
warnings.filterwarnings('ignore')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from meta import CH
P_ = '/home/ubuntu/cambc-autumn/research/ideas-2026-11-09/freshgate-tools/'
NAMES = json.load(open(P_ + 'names.json'))
L128 = {x['name'].replace('_', '-'): x['f'] for x in map(json.loads, open('/home/ubuntu/tmp-offload/diverse/fresh/feat-ladder.jsonl'))}
FT = dict(L128); FT.update({x['name'].replace('_', '-'): x['f'] for x in map(json.loads, open(os.path.expanduser('~/tmp-offload/fishr8/feat-05.jsonl')))})
C = 0.3
EXP = ('dash_gain', 'narrow', 'spawn_ring', 'max_group', 'camp_altar', 'sight_gap')
KEEP = np.array([not any(e in n for e in EXP) for n in NAMES])
def raw(f): return np.array([0.0 if f.get(n) is None or not np.isfinite(f.get(n)) else float(f[n]) for n in NAMES])
X0 = np.array([raw(f) for f in L128.values()]); MU, SD = X0.mean(0), X0.std(0); SD[SD < 1e-9] = 1.0
def z(f): return np.clip((raw(f) - MU) / SD, -4, 4) * KEEP
enum = lambda n: n.lower().replace(' & ', '_and_').replace(' ', '_')
FULL = {'Vesper': 'Vesper Vale', 'C&I': 'Cassi & Issac', 'HoR': 'Heart of Ruin'}
o = json.load(open(os.path.expanduser('~/tmp-offload/fishr8/ours.json')))
cnt = collections.defaultdict(collections.Counter); order = collections.defaultdict(collections.Counter)
for v in o.values():
    if v['refset'] != 'r8': continue
    m = v['map'].replace('_', '-')
    if m not in FT: continue
    p = [FULL.get(CH[i], CH[i]) for i in v['opp_picks']]
    comp = '|'.join(sorted(p)); cnt[m][comp] += 1; order[comp][tuple(p)] += 1
out = {}
for P in (3, 4, 5):
    maps = [m for m in cnt if len(next(iter(cnt[m])).split('|')) == P]
    rows = [(m, c, w / sum(cnt[m].values())) for m in maps for c, w in cnt[m].items()]
    X = np.array([z(FT[m]) for m, _, _ in rows]); y = [c for _, c, _ in rows]; w = np.array([x for *_, x in rows])
    comps = sorted(set(y)); acc = ovl = base = 0.0
    for m in maps:
        tr = [i for i, r in enumerate(rows) if r[0] != m]; yt = [y[i] for i in tr]
        pred = yt[0] if len(set(yt)) < 2 else LogisticRegression(C=C, max_iter=3000).fit(X[tr], yt, sample_weight=w[tr]).predict(z(FT[m])[None])[0]
        tot = sum(cnt[m].values()); acc += cnt[m][pred] / tot
        ovl += sum(v / tot * len(set(pred.split('|')) & set(c.split('|'))) / P for c, v in cnt[m].items())
        mc = collections.Counter(); [mc.update({c: ww}) for (mm, c, ww) in rows if mm != m]; base += cnt[m][mc.most_common(1)[0][0]] / tot
    n = len(maps)
    print(f'F picks {P}: {n} maps, {len(comps)} comps; held-out exact comp {acc/n:.2f} (modal baseline {base/n:.2f}), champion overlap {ovl/n:.2f}')
    if len(comps) == 1: b = np.zeros(1); W = np.zeros((1, len(NAMES)))
    else:
        model = LogisticRegression(C=C, max_iter=3000).fit(X, y, sample_weight=w); assert list(model.classes_) == comps
        b, W = model.intercept_, model.coef_
        if len(comps) == 2: b = np.array([0.0, b[0]]); W = np.vstack([np.zeros(len(NAMES)), W[0]])
    out[P] = [(c, list(order[c].most_common(1)[0][0]), float(b[i]), W[i]) for i, c in enumerate(comps)]
L = ['#pragma once', "// Generated by research/ideas-2026-11-12/fishr8/fitgen.py: Fish r8's pick model.",
     '// Multinomial logit over the comps it drafted in our scrims (170 ranked maps), on the 92 draft-lab map features',
     '// (draft/map_features.h names order) standardised over the 128 ladder maps and clamped at +-4, a NaN read as 0.',
     '#include <cstdint>', 'namespace fm {', 'using C = cambc::champion_draft;', 'inline constexpr bool sample = false;',
     'inline constexpr double mu[92] = {' + ', '.join(f'{v:.10g}' for v in MU) + '};',
     'inline constexpr double sd[92] = {' + ', '.join(f'{v:.10g}' for v in SD) + '};',
     'struct Comp { int n; C picks[5]; double b; double w[92]; };', 'inline constexpr Comp comps[] = {']
for P in (3, 4, 5):
    for c, ordr, b, W in out[P]:
        L.append(f"    {{{P}, {{{', '.join('C::' + enum(p) for p in ordr)}}}, {b:.10g}, {{{', '.join(f'{v:.8g}' for v in W)}}}}}, // {c}")
L += ['};', '}', '']
open(os.path.join(sys.argv[1], 'fm_draft_F.h'), 'w').write('\n'.join(L)); print('wrote', sys.argv[1])
